// The bundler: index.html with every <script src> inlined into one file in the folder's root, window.FF_ABOUT from
// src/about.json, and exit-interview.json written from the same object (so the About screen and the file agree).
import { readFileSync, writeFileSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
const NAME = 'HamericanFootball-AmericanFootball-claude-opus-5-5-medium-20261104-070556';
const here = p => new URL(p, import.meta.url);
const about = JSON.parse(readFileSync(here('src/about.json'), 'utf8'));
// the About data as a script the dev page and the bundle both load
writeFileSync(here('src/about.js'), '/* generated by build.mjs from src/about.json: the About & Credits pages and exit-interview.json */\nwindow.FF_ABOUT = ' + JSON.stringify(about, null, 1) + ';\n');
const html = readFileSync(here('index.html'), 'utf8');
const esc = s => s.replace(/<\/script/gi, '<\\/script');
let sessionHash = '';
let out = html.replace(/<script src="([^"]+)"><\/script>/g, (m, f) => {
  const text = readFileSync(here(f), 'utf8');
  if (f.endsWith('session.js')) sessionHash = createHash('sha256').update(text).digest('hex');
  return '<script>' + esc(text) + '</script>';
});
if (!out.includes('window.FF_ABOUT')) throw new Error('FF_ABOUT not inlined');
const dest = here('../' + NAME + '.html');
writeFileSync(dest, out);
// the exit interview: exactly the shape TASK.md gives
const ei = { sourceInformation: about.sourceInformation, testingFeedback: about.testingFeedback, engineFeedback: about.engineFeedback, promptFeedback: about.promptFeedback, aiHub: about.aiHub };
writeFileSync(here('../exit-interview.json'), JSON.stringify(ei, null, 2) + '\n');
JSON.parse(readFileSync(here('../exit-interview.json'), 'utf8'));
const vendorHash = createHash('sha256').update(readFileSync(here('vendor/session.js'), 'utf8')).digest('hex');
const sessionStart = out.indexOf('<script>') , firstScript = out.slice(sessionStart, sessionStart + 60);
console.log(`wrote ${NAME}.html: ${(statSync(dest).size / 1048576).toFixed(2)} MB; session.js sha256 ${sessionHash.slice(0, 16)} ${sessionHash === vendorHash ? 'matches' : 'DIFFERS'}; first script: ${firstScript.includes('aihub') || firstScript.includes('AIHub') || out.indexOf('<script>') < out.indexOf('hub:session') ? 'session.js' : '?'}`);
