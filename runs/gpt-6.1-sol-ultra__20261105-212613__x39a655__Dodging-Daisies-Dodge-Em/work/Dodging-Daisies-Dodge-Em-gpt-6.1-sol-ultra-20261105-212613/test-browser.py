"""Assembled single-file game integration checks. One browser, ephemeral local server."""
import functools
import http.server
import json
import pathlib
import threading
import sys
from playwright.sync_api import sync_playwright
ROOT=pathlib.Path(__file__).parent
class Quiet(http.server.SimpleHTTPRequestHandler):
    def log_message(self,*args): pass
server=http.server.ThreadingHTTPServer(('127.0.0.1',0),functools.partial(Quiet,directory=str(ROOT)))
threading.Thread(target=server.serve_forever,daemon=True).start()
origin=f'http://127.0.0.1:{server.server_address[1]}'
checks=0;failures=[];errors=[]
def check(name,fn):
    global checks
    checks+=1
    (ROOT/'browser-test-progress.json').write_text(json.dumps({'check':checks,'name':name}))
    try: fn()
    except Exception as e: failures.append(f'{name}: {e}');print(f'FAIL {name}: {e}')
def eq(a,b): assert a==b,f'{a!r} != {b!r}'
def truth(a): assert a,repr(a)
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,args=['--enable-unsafe-webgpu','--enable-features=Vulkan','--use-webgpu-adapter=swiftshader'])
    context=browser.new_context(viewport={'width':1440,'height':1000})
    page=context.new_page()
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(origin+'/index.html?renderer=webgl')
    page.wait_for_function('window.__DD?.ready || window.__bootError',timeout=120000)
    check('single file starts',lambda:truth(page.evaluate('!!window.__DD?.ready')))
    if page.evaluate('!!window.__DD?.ready'):
      check('fallback backend and native animations',lambda:truth(page.evaluate("__DD.renderer.backend==='WebGL 2 fallback' && __DD.renderer.nativeAnimations>0")))
      check('title and initial music volume',lambda:eq(page.evaluate('[__DD.state.mode,__DD.audio.musicVolume]'),['title',.1]))
      page.get_by_role('button',name='HOW TO PLAY',exact=True).click()
      check('instructions cover all four rules',lambda:eq(page.locator('.instructionCard').count(),4))
      page.keyboard.press('Escape')
      page.get_by_role('button',name='SETTINGS',exact=True).click()
      page.locator('#music').evaluate("e=>{e.value=.23;e.dispatchEvent(new Event('input',{bubbles:true}))}")
      page.locator('#padStyle').select_option('xbox')
      check('live settings and prompt preference',lambda:eq(page.evaluate('__DD.audio.musicVolume'),.23))
      page.locator('#mute').focus();page.keyboard.press('Space')
      check('keyboard confirm toggles focused checkbox',lambda:eq(page.evaluate('[__DD.audio.muted,__DD.menu]'),[True,'settings']))
      page.keyboard.press('Space')
      page.keyboard.press('Escape')
      page.get_by_role('button',name='LET’S ROLL').click()
      check('solo countdown',lambda:eq(page.evaluate('[__DD.state.mode,__DD.state.playerCount]'),['playing',1]))
      page.evaluate('__DD.game.state.countdown=0')
      before=page.evaluate('__DD.state.players[0].t')
      page.wait_for_timeout(350)
      check('auto forward and Rapier steps',lambda:truth(page.evaluate(f'__DD.state.players[0].t!={before} && __DD.physics.steps>0')))
      page.keyboard.press('KeyW');page.wait_for_function('__DD.state.players[0].queue>0 || __DD.state.players[0].lane>0')
      check('keyboard queues inward lane',lambda:truth(page.evaluate('__DD.state.players[0].queue>0 || __DD.state.players[0].lane>0')))
      page.keyboard.down('Space')
      page.wait_for_function('__DD.state.players[0].boost')
      check('hold accelerator',lambda:truth(page.evaluate('__DD.state.players[0].boost')))
      page.keyboard.up('Space')
      page.keyboard.press('KeyE')
      page.wait_for_function('__DD.state.players[0].pulse>0')
      check('keyboard triggers charged shield',lambda:truth(page.evaluate('__DD.state.players[0].pulse>0 && __DD.state.pulse<20')))
      page.keyboard.press('Escape')
      check('pause menu accessible',lambda:eq(page.evaluate('[__DD.state.mode,__DD.menu]'),['paused','pause']))
      before=page.evaluate('__DD.state.players[0].t');page.wait_for_timeout(200)
      check('pause freezes simulation',lambda:eq(page.evaluate('__DD.state.players[0].t'),before))
      page.get_by_role('button',name='TUNE THE CIRCUIT').click()
      page.locator('#speed').evaluate("e=>{e.value=12;e.dispatchEvent(new Event('input',{bubbles:true}))}")
      page.locator('#god').check()
      check('live developer balance controls',lambda:eq(page.evaluate('[__DD.settings.speed,__DD.settings.god]'),[12,True]))
      page.get_by_role('button',name='RESET DEFAULTS',exact=True).click()
      check('developer defaults restore',lambda:eq(page.evaluate('[__DD.settings.speed,__DD.settings.god]'),[8.6,False]))
      page.locator('#devStage').select_option('4')
      check('developer stage jump',lambda:eq(page.evaluate('__DD.state.stage'),4))
      page.get_by_role('button',name='TAKE IT FOR A SPIN').click()
      page.evaluate('__DD.game.state.countdown=0')
      page.wait_for_function('__DD.state.gateOpen.filter(Boolean).length===3')
      check('final circuit gates and enemies',lambda:truth(page.evaluate('__DD.state.enemies.length===2&&__DD.state.gateOpen.filter(Boolean).length===3')))
      page.evaluate('__DD.returnTitle()')
      page.get_by_role('button',name='TWO DRIVERS').click()
      page.get_by_role('button',name='COUCH CO-OP').click()
      page.evaluate('__DD.game.state.countdown=0')
      page.keyboard.press('ArrowUp');page.wait_for_function('__DD.state.players[1].queue>0||__DD.state.players[1].lane>2')
      check('second keyboard driver separate',lambda:truth(page.evaluate('__DD.state.players.length===2 && (__DD.state.players[1].queue>0||__DD.state.players[1].lane>2)')))
      page.keyboard.down('ShiftRight');page.wait_for_function('__DD.state.players[1].boost')
      check('second driver accelerator',lambda:truth(page.evaluate('__DD.state.players[1].boost')))
      page.keyboard.up('ShiftRight')
      page.evaluate('__DD.pause()')
      page.get_by_role('button',name='BACK TO THE CLUBHOUSE').click()
      page.get_by_role('button',name='ABOUT',exact=True).click()
      check('credits required source fields',lambda:eq(page.locator('.creditsList dt').count(),15))
      page.get_by_role('button',name='TESTING FEEDBACK',exact=True).click()
      check('credits testing feedback',lambda:eq(page.locator('.feedbackList li').count(),4))
      page.get_by_role('button',name='ENGINE FEEDBACK',exact=True).click()
      check('credits engine feedback',lambda:eq(page.locator('.feedbackList li').count(),6))
      page.get_by_role('button',name='PROMPT FEEDBACK',exact=True).click()
      check('credits prompt feedback',lambda:eq(page.locator('.feedbackList li').count(),4))
      page.keyboard.press('Escape')
      page.evaluate('__DD.returnTitle()')
      page.evaluate('''window.pad={index:0,id:'Test DualSense',connected:true,mapping:'standard',axes:[0,0,0,0],buttons:Array.from({length:18},()=>({pressed:false,value:0}))};Object.defineProperty(navigator,'getGamepads',{value:()=>[pad]});''')
      page.evaluate('pad.buttons[0]={pressed:true,value:1}')
      page.wait_for_function('__DD.state.mode==="playing"&&__DD.input==="gamepad"')
      page.evaluate('pad.buttons[0]={pressed:false,value:0}')
      check('standard controller starts same game',lambda:eq(page.evaluate('[__DD.state.mode,__DD.input]'),['playing','gamepad']))
      page.evaluate('__DD.game.state.countdown=0;pad.axes[1]=-1')
      page.wait_for_function('__DD.state.players[0].queue>0||__DD.state.players[0].lane>0')
      check('controller stick queues steering',lambda:truth(page.evaluate('__DD.state.players[0].queue>0||__DD.state.players[0].lane>0')))
      page.evaluate('pad.axes[1]=0;pad.buttons[9]={pressed:true,value:1}')
      page.wait_for_function('__DD.menu==="pause"')
      check('controller Options pauses',lambda:eq(page.evaluate('__DD.menu'),'pause'))
      page.evaluate('pad.buttons[9]={pressed:false,value:0};pad.buttons[1]={pressed:true,value:1}')
      page.wait_for_function('__DD.state.mode==="playing"')
      check('controller cancel resumes',lambda:eq(page.evaluate('__DD.state.mode'),'playing'))
      page.evaluate('pad.buttons[1]={pressed:false,value:0};__DD.returnTitle()')
      # Advance the real page clock without executing simulation thousands of times.
      try: page.wait_for_function('__DD.state.attract',timeout=22000)
      except Exception:
        (ROOT/'attract-diagnostics.json').write_text(json.dumps(page.evaluate('({debug:__DD.debug,state:__DD.state,errors:window.__renderError})'),indent=2))
      check('10 second idle starts attract play',lambda:truth(page.evaluate('__DD.state.attract && __DD.state.mode==="attract"')))
      page.keyboard.press('KeyW');page.wait_for_function('__DD.state.mode==="title"')
      check('any input exits attract',lambda:eq(page.evaluate('__DD.state.mode'),'title'))

      # Exercise the actual Rapier collision callback at overlapping car positions.
      page.evaluate('''__DD.play(1);let s=__DD.game.state;s.countdown=0;s.players[0].invincible=0;s.players[0].pulse=0;s.players[0].t=.1;s.enemies[0].t=.1;s.players[0].lane=s.enemies[0].lane=0;s.players[0].renderLane=s.enemies[0].renderLane=0;__DD.step(2);''')
      check('Rapier collision consumes one spare',lambda:eq(page.evaluate('__DD.state.lives'),2))
      # Full source mechanics in assembled renderer/physics build, shielded AI for repeatability.
      page.evaluate('''__DD.play(1);__DD.game.autopilot=true;__DD.game.settings.god=true;__DD.game.state.countdown=0;__DD.step(7000);''')
      check('assembled four-stage full playthrough',lambda:eq(page.evaluate('[__DD.state.mode,__DD.state.flowers,__DD.state.stage]'),['victory',320,4]))
      check('result screen',lambda:eq(page.evaluate('__DD.menu'),'result'))
      page.keyboard.press('Escape')
      check('result back returns to title',lambda:eq(page.evaluate('__DD.state.mode'),'title'))
      check('audio graph produces real signal',lambda:truth(page.evaluate('__DD.audio.unlocked&&__DD.audio.scheduledNotes>0')))
      check('no game or rendering exceptions',lambda:eq(errors+page.evaluate('[window.__renderError].filter(Boolean)'),[]))
    context.close();browser.close()
    browser=p.chromium.launch(headless=True,args=['--enable-unsafe-webgpu','--enable-features=Vulkan','--use-webgpu-adapter=swiftshader'])
    # Screenshot the same native renderer with its supported fallback for readable headless capture.
    file_context=browser.new_context()
    f=file_context.new_page();f.goto((ROOT/'index.html').as_uri()+'?renderer=webgl');f.wait_for_function('window.__DD?.ready',timeout=90000)
    check('self-contained file URL starts',lambda:truth(f.evaluate('__DD.ready&&__DD.state.dots.length===80')))
    file_context.close()
    visual=browser.new_context(viewport={'width':1440,'height':1000},has_touch=False)
    v=visual.new_page();v.goto(origin+'/index.html?renderer=webgl');v.wait_for_function('window.__DD?.ready',timeout=120000);v.wait_for_timeout(1500)
    v.screenshot(path=str(ROOT/'title-final.png'))
    v.evaluate('__DD.play(1);__DD.game.state.countdown=0;__DD.game.settings.god=true;__DD.game.state.players[0].invincible=0')
    v.wait_for_timeout(1200);v.screenshot(path=str(ROOT/'gameplay-final.png'))
    visual.close()
    mobile=browser.new_context(viewport={'width':390,'height':844},device_scale_factor=1,is_mobile=True,has_touch=True)
    m=mobile.new_page();mobile_errors=[];m.on('pageerror',lambda e:mobile_errors.append(str(e)));m.goto(origin+'/index.html?renderer=webgl');m.wait_for_function('window.__DD?.ready',timeout=120000)
    m.get_by_role('button',name='LET’S ROLL').tap();m.evaluate('__DD.game.state.countdown=0')
    m.evaluate("document.querySelector('canvas').dispatchEvent(new PointerEvent('pointerdown',{pointerType:'touch',pointerId:3,clientX:100,clientY:500,bubbles:true}));document.querySelector('canvas').dispatchEvent(new PointerEvent('pointermove',{pointerType:'touch',pointerId:3,clientX:100,clientY:450,bubbles:true}));")
    m.wait_for_function('__DD.state.players[0].queue>0||__DD.state.players[0].lane>0')
    check('touch swipe queues steering',lambda:truth(m.evaluate('__DD.state.players[0].queue>0||__DD.state.players[0].lane>0')))
    check('touch minimal HUD',lambda:truth(m.evaluate('document.body.classList.contains("touchMode")')))
    m.locator('#pulseButton').tap();m.wait_for_function('__DD.state.players[0].pulse>0')
    check('contextual touch shield',lambda:truth(m.evaluate('__DD.state.players[0].pulse>0')))
    check('touch page has no exceptions',lambda:eq(mobile_errors,[]))
    m.screenshot(path=str(ROOT/'mobile-final.png'))
    mobile.close();browser.close()
server.shutdown();server.server_close()
(ROOT/'browser-test-results.json').write_text(json.dumps({'checks':checks,'failures':failures,'pageErrors':errors},indent=2))
print(f'{checks-len(failures)}/{checks} browser checks passed; {len(failures)} failed.')
sys.exit(bool(failures))
