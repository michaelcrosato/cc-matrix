//! Sound cues for Tempo Trauma (`SimEvent::Cue`): about thirty-five synthesized sounds.

use crate::{Patch, Wave};

fn p(w: Wave, f: f32, f2: f32, glide: f32, a: f32, d: f32, r: f32, vol: f32) -> Patch {
    let mut x = Patch::new(w, f);
    x.freq_end = f2;
    x.glide = glide;
    x.attack = a;
    x.decay = d;
    x.release = r;
    x.volume = vol;
    x
}

fn noise(cut0: f32, cut1: f32, d: f32, vol: f32) -> Patch {
    let mut x = p(Wave::Noise, 200.0, 200.0, 0.1, 0.002, d, 0.03, vol);
    x.cutoff = cut0;
    x.cutoff_end = cut1;
    x
}

