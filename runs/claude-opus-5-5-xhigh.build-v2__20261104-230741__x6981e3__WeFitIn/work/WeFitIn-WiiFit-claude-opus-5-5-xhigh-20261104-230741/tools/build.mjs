// Bundle everything into one html in root, and write the exit interview from src/data/about.js.
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const DEV = join(dirname(fileURLToPath(import.meta.url)), '..');
process.chdir(DEV);
const { BASE_NAME, TITLE } = await import('../src/data/title.js');

// The kit asks for CREDITS.md to be shipped: it becomes a data module the About screen reads.
const credits = readFileSync('CREDITS.md', 'utf8');
writeFileSync('src/data/credits-text.js', `// Generated by tools/build.mjs from the kit's CREDITS.md.\nexport const CREDITS_TEXT = ${JSON.stringify(credits)};\n`);

mkdirSync('.build', { recursive: true });
execFileSync('esbuild', ['src/main.js', '--bundle', '--format=esm', '--platform=browser', '--target=esnext', '--charset=utf8', '--outfile=.build/bundle.js', '--log-level=warning'], { stdio: 'inherit' });

const HUB_METAS = `<meta name="hub:session" content="1">
<meta name="hub:session-players" content="1-4">
<meta name="hub:session-mode" content="ghost">
<meta name="hub:session-goal" content="Score the most across three events. Stay in the circle.">
<meta name="hub:session-howto" content="Left stick, WASD or mouse: lean. R2, Space or click: breathe. L1/R1, F/J: step.">
<meta name="hub:session-minutes" content="4">
<meta name="hub:webgpu" content="required">`;

const safe = (s) => s.replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--');
const html = `<!doctype html>
<html lang="en"><head>
<meta charset="utf-8">
<script>${readFileSync('vendor/hub/session.js', 'utf8')}</script>
${HUB_METAS}
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover">
<link rel="icon" href="data:,"><title>${TITLE}</title>
<style>html, body { margin: 0; height: 100%; background: #0d0b14; } #app { position: fixed; inset: 0; }</style>
</head><body><div id="app"></div>
<script type="module">${safe(readFileSync('.build/bundle.js', 'utf8'))}</script>
</body></html>`;
const OUTPUT_HTML = join('..', `${BASE_NAME}.html`);
writeFileSync(OUTPUT_HTML, html);

const { exitInterview } = await import('../src/data/about.js');
const exitPath = join('..', 'exit-interview.json');
writeFileSync(exitPath, `${JSON.stringify(exitInterview(), null, 2)}\n`);
JSON.parse(readFileSync(exitPath, 'utf8'));
