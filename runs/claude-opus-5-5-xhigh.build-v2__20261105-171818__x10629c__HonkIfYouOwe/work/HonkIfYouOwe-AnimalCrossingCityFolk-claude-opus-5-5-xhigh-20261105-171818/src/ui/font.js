export const GLYPHS = {};
for (const [ch, s] of Object.entries(G)) {
  const rows = s.split('/');
  const w = Math.max(...rows.map((r) => r.length));
  GLYPHS[ch] = { rows: rows.map((r) => r.padEnd(w, '.')), w, skip: false };
}
const SPACE_W = 3;
const COLOR = (c) => ({ '#': c });
const colorCache = new Map();
const col = (c) => { let v = colorCache.get(c); if (!v) colorCache.set(c, (v = COLOR(c))); return v; };

export const LINE_H = 12;

/** Width of a string (plain characters) in art pixels at a scale. */
export function textWidth(s, scale = 1) {
  let w = 0;
  for (const ch of s) {
    const g = GLYPHS[ch];
    w += (g ? g.w : SPACE_W) + 1;
  }
  return Math.max(0, (w - 1) * scale);
}

/** Draws a string; x,y is the top left of the caps. Returns the width. Unknown characters draw as spaces. */
export function drawText(hud, x, y, s, o = {}) {
  const { color = 'ink', scale = 1, shadow = false, align = 'left' } = o;
  let cx = x;
  if (align !== 'left') {
    const w = textWidth(s, scale);
    cx = align === 'center' ? x - Math.floor(w / 2) : x - w;
  }
  const start = cx;
  const sc = scale === 1 ? NOSHADOW1 : { shadow: false, scale };
  for (const ch of s) {
    const g = GLYPHS[ch];
    if (!g) { cx += (SPACE_W + 1) * scale; continue; }
    if (shadow) hud.sprite(cx + scale, y + scale, g.rows, col(shadow), sc);
    hud.sprite(cx, y, g.rows, col(color), sc);
    cx += (g.w + 1) * scale;
  }
  return cx - start;
}
const NOSHADOW1 = { shadow: false };

/** Word wrap to a pixel width. Keeps explicit \n. Markup characters (* and |) are treated as zero width. */
export function wrap(s, width, scale = 1) {
  const lines = [];
  for (const para of s.split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const trial = line ? `${line} ${word}` : word;
      if (textWidth(trial.replace(/[*|]/g, ''), scale) > width && line) { lines.push(line); line = word; } else line = trial;
    }
    lines.push(line);
  }
  return lines;
}
