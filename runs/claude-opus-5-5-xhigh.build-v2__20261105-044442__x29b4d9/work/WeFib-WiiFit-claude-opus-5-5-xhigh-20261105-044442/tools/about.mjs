// Writes src/data/about.js from the exit interview, so the three places can't disagree.
const KEYS = {
  date: 'Date', source: 'Source', plan: 'Plan', genre: 'Genre', perspective: 'Perspective', tech: 'Tech', artDirection: 'Art Direction', animation: 'Animation',
  audio: 'Audio', online: 'Online', testing: 'Testing', research: 'Research', environment: 'Environment', model: 'Model', usage: 'Usage',
};
const blank = {
  sourceInformation: Object.fromEntries(Object.keys(KEYS).map((k) => [k, k === 'usage' ? 'added on import' : 'unknown'])),
  testingFeedback: ['unknown', 'unknown', 'unknown', 'unknown'], engineFeedback: ['unknown', 'unknown', 'unknown', 'unknown', 'unknown', 'unknown'], promptFeedback: ['unknown', 'unknown', 'unknown', 'unknown'],
};
export function aboutFromInterview(j) {
  const d = j || blank;
  return `// Generated by tools/build.mjs from the exit interview.
export const ABOUT = ${JSON.stringify({ sourceInformation: d.sourceInformation, testingFeedback: d.testingFeedback, engineFeedback: d.engineFeedback, promptFeedback: d.promptFeedback }, null, 1)};
export const SOURCE_LABELS = ${JSON.stringify(KEYS)};
`;
}
