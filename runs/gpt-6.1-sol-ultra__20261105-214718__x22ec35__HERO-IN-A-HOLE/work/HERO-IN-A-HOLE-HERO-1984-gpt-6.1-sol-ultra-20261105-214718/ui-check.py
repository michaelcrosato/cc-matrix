from pathlib import Path
from playwright.sync_api import sync_playwright
import json
root = Path(__file__).parent
checks=0
failures=[]
def check(condition,message):
 global checks
 checks += 1
 if not condition: failures.append(message)
with sync_playwright() as p:
 browser = p.chromium.launch(headless=True)
 page = browser.new_page(viewport={"width":1920,"height":1080})
 page.set_content((root/'shell.html').read_text())
 page.add_script_tag(content=(root/'ui.js').read_text().replace('export class UI','class UI')+'\nwindow.actions=[];window.ui=new UI((action,data)=>actions.push({action,data}));document.getElementById("boot").remove();')
 page.wait_for_timeout(50)
 check(page.locator('[data-screen="title"]').is_visible(),'Title screen hidden')
 page.evaluate('ui.confirm()')
 check(page.evaluate('actions[0].action')=='start','Default confirm does not start')
 page.evaluate('ui.show("settings");ui.navigate(0,1);ui.navigate(1,0)')
 check(page.evaluate('actions.at(-1).action')=='setting','Range controller navigation does not emit setting')
 page.evaluate('ui.back()')
 check(page.evaluate('ui.screen')=='title','Settings back loses title screen')
 page.evaluate('ui.show(null);ui.show("pause");ui.show("dev");ui.navigate(0,1);ui.navigate(0,1);ui.navigate(1,0)')
 check(page.evaluate('actions.at(-1).action')=='tuning','Developer tuning does not emit')
 page.evaluate('ui.back()')
 check(page.evaluate('ui.screen')=='pause','Developer back loses pause screen')
 page.evaluate('ui.setInput("gamepad")')
 check('R2' in page.locator('#control-hints').inner_text(),'PlayStation input hints not updated')
 page.evaluate('ui.settings.glyphs="xbox";ui.setInput("gamepad")')
 check('RT' in page.locator('#control-hints').inner_text(),'Xbox hints not updated')
 page.evaluate('ui.setInput("touch");ui.show(null)')
 check(page.locator('#touch-bomb').is_visible(),'Touch bomb hidden during gameplay')
 page.evaluate('ui.show("title")')
 check(not page.locator('#touch-bomb').is_visible(),'Touch bomb leaks onto title')
 page.evaluate('ui.setOnlineStatus("Invite ready","HERO1.test");ui.show("online")')
 check(page.locator('#online-link').input_value()=='HERO1.test','Online output missing')
 page.locator('#online-code').fill('HERO1.answer')
 page.locator('[data-online="connect"]').click()
 check(page.evaluate('actions.at(-1).data.code')=='HERO1.answer','Online input code omitted')
 page.locator('[data-online="copy"]').click()
 check(page.evaluate('actions.at(-1).data.code')=='HERO1.test','Copy invitation uses partner code')
 page.evaluate('ui.setCredits({sourceInformation:{source:"H.E.R.O. 1984",usage:"added on import"},testingFeedback:["4","1","playthrough","unknown"]});ui.show("about")')
 check('H.E.R.O. 1984' in page.locator('#credits-content').inner_text(),'Credits missing source')
 check('print?print=1' in page.locator('#credits-content a').nth(1).get_attribute('href'),'Credits reference the wrong archived source page')
 page.locator('[data-credit-tab="testingFeedback"]').click()
 check('playthrough' in page.locator('#credits-content').inner_text(),'Feedback tab missing answers')
 page.evaluate('ui.setInput("keyboard");ui.show("title")')
 title_box=page.locator('.title-copy').bounding_box()
 check(title_box['y']+title_box['height']<1040,'Title content overlaps bottom at 1080p')
 page.screenshot(path=str(root/'ui-title-1920.png'))
 page.set_viewport_size({'width':1280,'height':720})
 page.screenshot(path=str(root/'ui-title-1280.png'))
 title_box=page.locator('.title-copy').bounding_box()
 check(title_box['y']+title_box['height']<680,'Title content overlaps bottom at 720p')
 page.set_viewport_size({'width':390,'height':844})
 page.screenshot(path=str(root/'ui-title-phone.png'))
 title_box=page.locator('.title-copy').bounding_box()
 check(title_box['y']+title_box['height']<795,'Title content overlaps footer on phone')
 browser.close()
for failure in failures: print('FAIL:',failure)
print(f'{checks} UI checks, {len(failures)} failures')
raise SystemExit(bool(failures))
