# The paths a player takes that no other suite ever ran, found by tools/coverage.mjs. Driven through the real menus.
import sys, pathlib, json
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from _common import *

s = Suite()
LIVE = 'async () => { const e = await window.__PIXEL_READY__; e.manual = false; }'
AT_SHOP = '?g_area=quay&g_start=28,42&g_skip=arrival,tannoyHint,cottage,quayFront,shedHint,siege&g_noattract=1'
top = lambda page: page.evaluate('window.__APP__.top?.name ?? null')
focus = lambda page, name: page.evaluate('(n) => { window.__APP__.ui.focus = n; }', name)
def press(page, key, n=3):
    page.keyboard.press(key); step(page, n)

with sync_playwright() as pw:
    b = launch(pw)

    # ---- CONTINUE on the title: a save, a fresh page, and back where you were. ----
    ctx = b.new_context(viewport={'width': 960, 'height': 540})
    page = ctx.new_page()
    errs = []
    page.on('pageerror', lambda e: errs.append(str(e)))
    page.goto(DELIVERABLE.as_uri() + AT_SHOP)
    page.evaluate('async () => { await window.__PIXEL_READY__; }')
    step(page, 20)
    saved = page.evaluate("() => { const g = window.__GAME__; g.run.money = 1234; g.run.setFlag('testFlag'); g.checkpoint(g.entry); return { area: g.id, at: [g.level.info.col(g.player.x), g.level.info.row(g.player.z)] }; }")
    page.goto(DELIVERABLE.as_uri() + '?g_noattract=1')
    page.evaluate('async () => { await window.__PIXEL_READY__; }')
    step(page, 10)
    rects = page.evaluate('window.__APP__.ui.rects.map((r) => r.id)')
    s.ok(rects[:1] == ['continue'], f'the title offers CONTINUE first when a save exists ({rects})')
    focus(page, 'continue')
    page.evaluate(LIVE)
    page.keyboard.press('Enter')
    page.wait_for_function("() => window.__GAME__?.id === 'quay' && window.__GAME__.player", timeout=60000)
    got = page.evaluate("() => { const g = window.__GAME__; return { money: g.run.money, flag: g.run.flag('testFlag'), at: [g.level.info.col(g.player.x), g.level.info.row(g.player.z)], cp: !!g.run.checkpoint }; }")
    s.ok(got['money'] == 1234 and got['flag'], f'CONTINUE restores the run ({got})')
    s.ok(got['at'] == saved['at'], f'at the checkpoint ({got["at"]} vs {saved["at"]})')
    s.ok(got['cp'], 'and a death from here returns here')
    s.ok(errs == [], f'CONTINUE: no errors {errs[:2]}')
    ctx.close()

    # ---- The Case: pick up, rotate, place; can't place on another item; drop to the ground; no littering guns. ----
    page, errs = open_game(b, AT_SHOP + '&g_nosave=1')
    step(page, 20)
    page.evaluate("() => { const g = window.__GAME__; g.run.giveItem('samphire'); window.__SCREENS__.openCase(g); }")
    step(page, 3)
    st = lambda: page.evaluate("() => { const t = window.__APP__.top; const it = t.grid.items.find((i) => i.id === 'samphire'); return { held: t.state.held?.item?.id ?? null, rot: t.state.held?.item?.rot ?? null, x: it?.x ?? null, y: it?.y ?? null, itRot: it?.rot ?? null, menu: !!t.state.menu, cx: t.state.cx, cy: t.state.cy, drops: window.__GAME__.drops.length }; }")
    at = st()
    page.evaluate("(a) => { const t = window.__APP__.top; t.state.cx = a.x; t.state.cy = a.y; }", at)
    step(page, 2)
    press(page, 'Enter')
    s.ok(st()['menu'], 'Cross on an item opens its small menu')
    focus(page, 'm0'); press(page, 'Enter')
    s.ok(st()['held'] == 'samphire', 'MOVE picks it up')
    press(page, 'KeyR')
    s.ok(st()['rot'] is True, 'and it rotates in hand')
    free = page.evaluate("() => { const t = window.__APP__.top; const h = t.state.held.item; for (let y = 0; y < t.grid.h; y++) for (let x = 0; x < t.grid.w; x++) if (t.grid.fits(h, x, y)) return [x, y]; return null; }")
    blocked = page.evaluate("() => { const t = window.__APP__.top; const h = t.state.held.item; for (let y = 0; y < t.grid.h; y++) for (let x = 0; x < t.grid.w; x++) if (!t.grid.fits(h, x, y)) return [x, y]; return null; }")
    page.evaluate("(a) => { const t = window.__APP__.top; t.state.cx = a[0]; t.state.cy = a[1]; }", blocked)
    step(page, 2); press(page, 'Enter')
    s.ok(st()['held'] == 'samphire', 'it will not go where something already is')
    page.evaluate("(a) => { const t = window.__APP__.top; t.state.cx = a[0]; t.state.cy = a[1]; }", free)
    step(page, 2); press(page, 'Enter')
    placed = page.evaluate("(a) => { const t = window.__APP__.top; const it = t.grid.at(a[0], a[1]); return { id: it?.id ?? null, rot: it?.rot ?? null, held: t.state.held?.item?.id ?? null, n: t.grid.count('samphire') }; }", free)
    s.ok(placed['held'] is None and placed['id'] == 'samphire' and placed['rot'] is True, f'it places where there is room, rotated ({placed})')
    page.evaluate("(a) => { const t = window.__APP__.top; t.state.cx = a[0]; t.state.cy = a[1]; }", free)
    step(page, 2); press(page, 'Enter'); focus(page, 'm0'); press(page, 'Enter')
    drops0 = st()['drops']
    press(page, 'KeyX')
    now = st()
    left = page.evaluate("window.__APP__.top.grid.count('samphire')")
    s.ok(now['held'] is None and left == placed['n'] - 1, f'dropping leaves the Case ({now}, {left} of {placed["n"]})')
    s.ok(now['drops'] == drops0 + 1, 'and lands on the ground')
    gun = page.evaluate("() => { const t = window.__APP__.top; const it = t.grid.items.find((i) => i.id === 'pistol'); t.state.cx = it.x; t.state.cy = it.y; return true; }")
    step(page, 2); press(page, 'Enter'); focus(page, 'm0'); press(page, 'Enter')
    press(page, 'KeyX')
    s.ok(page.evaluate("window.__APP__.top.state.held?.item?.id") == 'pistol', 'a weapon cannot be littered')
    press(page, 'Escape')
    s.ok(page.evaluate("!!window.__APP__.top.grid.items.find((i) => i.id === 'pistol')"), 'Back puts it back')
    press(page, 'Escape')
    s.ok(top(page) is None, 'and the Case closes')
    # No room: the Case opens with the new item in hand, and the ground item stays until it's placed.
    page.evaluate("""() => { const g = window.__GAME__; const P = g.player; for (let i = 0; i < 200; i++) if (!g.run.case.add({ uid: 70000 + i, id: 'samphire', qty: 1, x: -1, y: -1, rot: false })) break; g.addDrop('item', 'flare', 1, P.x + Math.sin(P.facing) * 0.6, P.z + Math.cos(P.facing) * 0.6); }""")
    step(page, 4)
    cur = page.evaluate("window.__GAME__.interact.current?.kind ?? null")
    s.ok(cur == 'pick', f'a prompt for what is on the ground ({cur})')
    press(page, 'KeyE', 4)
    s.ok(top(page) == 'case' and page.evaluate("window.__APP__.top.state.held?.item?.id") == 'flare', f'no room: the Case opens with it in hand ({top(page)})')
    grounded = page.evaluate("window.__GAME__.drops.some((d) => d.id === 'flare')")
    s.ok(grounded, 'and it stays on the ground for now')
    press(page, 'Escape')
    s.ok(page.evaluate("window.__GAME__.drops.some((d) => d.id === 'flare')"), 'leaving it there is allowed')
    page.evaluate("() => window.__APP__.closeAll()"); step(page, 3)
    s.ok(errs == [], f'Case: no errors {errs[:2]}')
    page.close()

    # ---- Every dev tool, through its row. ----
    page, errs = open_game(b, AT_SHOP + '&g_nosave=1')
    step(page, 20)
    page.evaluate("() => { window.__SCREENS__.openDev(window.__GAME__); }"); step(page, 3)
    labels = page.evaluate("() => window.__APP__.ui.rects.map((r) => r.id)")
    want_rows = ['tgod', 'tnoclip', 'tinfiniteAmmo', 'toneHit', 'tfreezeAi', 'tshowZones', 'tshowNav', 'tshowTriggers', 'speed', 'a0', 'a1', 'a2', 'a3', 'a4', 'a5', 'a6', 'a7']
    s.ok(all(r in labels for r in want_rows), f'every tool has a row ({[r for r in want_rows if r not in labels]})')
    for key in ['god', 'noclip', 'infiniteAmmo', 'oneHit', 'freezeAi', 'showZones', 'showNav', 'showTriggers']:
        focus(page, f't{key}'); press(page, 'Enter')
        s.ok(page.evaluate(f"window.__APP__.dev.{key}") is True, f'{key} switches on')
        step(page, 5)
        focus(page, f't{key}'); press(page, 'Enter')
        s.ok(page.evaluate(f"window.__APP__.dev.{key}") is False, f'and off')
    focus(page, 'speed'); press(page, 'Enter')
    s.ok(page.evaluate("window.__APP__.devSpeed") != 1, 'game speed changes')
    for _ in range(3):
        if page.evaluate("window.__APP__.devSpeed") == 1: break
        focus(page, 'speed'); press(page, 'Enter')
    page.evaluate("() => { window.__GAME__.player.hp = 5; }")
    focus(page, 'a1'); press(page, 'Enter')
    s.ok(page.evaluate("window.__GAME__.player.hp === window.__GAME__.player.maxHp"), 'HEAL heals')
    m0 = page.evaluate("window.__GAME__.run.money")
    focus(page, 'a2'); press(page, 'Enter')
    s.ok(page.evaluate("window.__GAME__.run.money") == m0 + 10000, 'GIVE 10,000 DOUBLOONS')
    focus(page, 'a3'); press(page, 'Enter')
    gave = page.evaluate("() => { const r = window.__GAME__.run; return { w: r.ownedWeapons().length, flare: r.case.count('flare'), level: r.caseLevel }; }")
    s.ok(gave['w'] == 4 and gave['flare'] >= 1 and gave['level'] == 2, f'GIVE ALL WEAPONS AND ITEMS ({gave})')
    focus(page, 'a4'); press(page, 'Enter')
    s.ok(not page.evaluate("window.__GAME__.run.case.add({ uid: 80000, id: 'samphire', qty: 1, x: -1, y: -1, rot: false })"), 'FILL CASE fills it')
    page.evaluate("() => window.__APP__.top.setTab(2)"); step(page, 3)
    spawns = page.evaluate("window.__APP__.ui.rects.map((r) => r.id)")
    s.ok(len([r for r in spawns if r.startswith('sp')]) >= 12, f'SPAWN lists every enemy ({len(spawns)})')
    for sp in [r for r in spawns if r.startswith('sp')]:
        n0 = page.evaluate("window.__GAME__.enemies.filter((e) => !e.dead).length")
        focus(page, sp); press(page, 'Enter')
        s.ok(page.evaluate("window.__GAME__.enemies.filter((e) => !e.dead).length") == n0 + 1, f'{sp} spawns one')
    page.evaluate("() => window.__APP__.top.setTab(0)"); step(page, 3)
    alive = page.evaluate("window.__GAME__.enemies.filter((e) => !e.dead).length")
    s.ok(alive >= 12, f'{alive} alive')
    focus(page, 'a5'); press(page, 'Enter')
    s.ok(page.evaluate("window.__GAME__.enemies.filter((e) => !e.dead).length") == 0, 'KILL ALL')
    locked = page.evaluate("window.__GAME__.level.doors.filter((d) => d.locked).length")
    focus(page, 'a6'); press(page, 'Enter')
    u = page.evaluate("() => { const g = window.__GAME__; return { locked: g.level.doors.filter((d) => d.locked).length, gatesShut: g.level.gates.filter((x) => !x.open).length }; }")
    s.ok(u['locked'] == 0 and u['gatesShut'] == 0, f'UNLOCK ALL (from {locked} locked: {u})')
    focus(page, 'a7'); press(page, 'Enter')
    s.ok(page.evaluate("async () => (await window.__PIXEL_READY__).debugShown") is True, 'ENGINE DEBUG PANEL')
    focus(page, 'a7'); press(page, 'Enter')
    page.evaluate("() => { window.__GAME__.chapterCard('X'); }")
    focus(page, 'a0'); press(page, 'Enter')
    s.ok(errs == [], f'dev tools: no errors {errs[:2]}')
    page.close()
    # On each boss.
    page, errs = open_game(b, '?g_area=nave&g_nosave=1&g_noattract=1&g_start=13,30')
    step(page, 30)
    page.evaluate("() => { const g = window.__GAME__; g.bossLive = true; window.__SCREENS__.openDev(g); }"); step(page, 3)
    focus(page, 'a5'); press(page, 'Enter')
    s.ok(page.evaluate("window.__GAME__.bath.state") == 'OPEN', f'KILL ALL takes the Bathysphere to its hatch ({page.evaluate("window.__GAME__.bath.state")})')
    s.ok(errs == [], f'dev tools on a boss: no errors {errs[:2]}')
    page.close()

    # ---- Settings: the option rows, by key and by click, all three pages. ----
    page, errs = open_game(b, '?g_noattract=1&g_nosave=1')
    step(page, 10)
    page.evaluate("window.__SCREENS__.openSettings()"); step(page, 3)
    page.evaluate("window.__APP__.top.setPage(1)"); step(page, 3)
    v = lambda k: page.evaluate(f"window.__APP__.settings.{k}")
    g0 = v('glyphs')
    focus(page, 'glyphs'); press(page, 'ArrowRight')
    g1 = v('glyphs')
    s.ok(g1 != g0, f'CONTROLLER GLYPHS changes by key ({g0} > {g1})')
    press(page, 'ArrowLeft')
    s.ok(v('glyphs') == g0, 'and back')
    focus(page, 'glyphs'); press(page, 'Enter')
    s.ok(v('glyphs') == g1, 'and by confirm')
    focus(page, 'invert'); inv = v('invertY'); press(page, 'Enter')
    s.ok(v('invertY') != inv, 'INVERT Y toggles')
    page.evaluate("window.__APP__.top.setPage(2)"); step(page, 3)
    for key, row in [('look', 'look'), ('pixelSize', 'pixel'), ('quality', 'quality'), ('fps', 'fps')]:
        before = v(key)
        focus(page, row); press(page, 'ArrowRight', 6)
        s.ok(v(key) != before, f'{key} cycles ({before} > {v(key)})')
    step(page, 10)
    s.ok(page.evaluate("async () => (await window.__PIXEL_READY__).errors?.length ?? 0") == 0, 'the picture options apply without error')
    page.evaluate("window.__APP__.top.setPage(0)"); step(page, 3)
    focus(page, 'reset'); press(page, 'Enter')
    s.ok(abs(v('music') - 0.1) < 0.001 and v('invertY') == inv and v('glyphs') == g0 and v('look') == page.evaluate("window.__APP__.defaultLook ?? window.__APP__.settings.look"), 'RESET TO DEFAULTS restores them')
    press(page, 'Escape')
    s.ok(errs == [], f'Settings: no errors {errs[:2]}')
    page.close()

    # ---- Losing the pointer lock mid-play pauses (Esc under pointer lock may not reach the page). ----
    page, errs = open_game(b, AT_SHOP + '&g_nosave=1')
    step(page, 20)
    page.evaluate("() => { const A = window.__APP__; A.lockWanted = true; A.releasedByUs = false; document.dispatchEvent(new Event('pointerlockchange')); }")
    step(page, 3)
    s.ok(top(page) == 'pause', f'the lock lost in play pauses ({top(page)})')
    press(page, 'Escape')
    s.ok(errs == [], f'pointer lock: no errors {errs[:2]}')
    page.close()

    # ---- The credits: Back finishes, and the finished claim is cleared. ----
    ctx = b.new_context(viewport={'width': 960, 'height': 540})
    page = ctx.new_page(); errs = []
    page.on('pageerror', lambda e: errs.append(str(e)))
    page.goto(DELIVERABLE.as_uri() + AT_SHOP)
    page.evaluate('async () => { await window.__PIXEL_READY__; }')
    step(page, 20)
    page.evaluate("() => { const g = window.__GAME__; g.checkpoint(g.entry); }")
    page.evaluate(LIVE)
    page.evaluate("() => { window.__SCREENS__.openCredits(window.__GAME__); }")
    page.wait_for_function("window.__APP__.top?.name === 'credits'", timeout=10000)
    page.wait_for_timeout(600)
    page.keyboard.press('Escape')
    page.wait_for_function("window.__GAME__?.name === 'title'", timeout=60000)
    page.wait_for_timeout(800)
    rects = page.evaluate('window.__APP__.ui.rects.map((r) => r.id)')
    s.ok('continue' not in rects and 'new' in rects, f'finishing the credits returns to a title with nothing to continue ({rects})')
    s.ok(errs == [], f'credits: no errors {errs[:2]}')
    ctx.close()

    # ---- Night Shift on your own: Options opens a small pause; QUIT SHIFT returns to the title. ----
    page, errs = open_game(b, '?g_noattract=1&g_nosave=1')
    page.evaluate(LIVE)
    page.evaluate("window.__SCREENS__.startSolo()")
    page.wait_for_function('() => window.__GAME__?.name === "area:shift" && window.__GAME__.session.time() > 0', timeout=90000)
    page.keyboard.press('Escape')
    page.wait_for_function("window.__APP__.top?.name === 'shift-pause'", timeout=10000)
    s.ok(True, 'a solo shift can be paused')
    page.wait_for_timeout(400)
    rects = page.evaluate('window.__APP__.ui.rects.map((r) => r.id)')
    s.ok(rects == ['resume', 'settings', 'quit'], f'with its own small menu ({rects})')
    focus(page, 'quit')
    page.wait_for_timeout(200)
    page.keyboard.press('Enter')
    page.wait_for_function("window.__GAME__?.name === 'title'", timeout=60000)
    s.ok(True, 'QUIT SHIFT returns to the title')
    s.ok(errs == [], f'solo pause: no errors {errs[:2]}')
    page.close()

    # ---- WebRTC codes through the real overlay: make a code, paste it, answer it, seat fills. ----
    ctx = b.new_context(viewport={'width': 960, 'height': 540})
    host = ctx.new_page(); guest = ctx.new_page(); errs = []
    for p in (host, guest):
        p.on('pageerror', lambda e: errs.append(str(e)))
        p.goto(DELIVERABLE.as_uri() + '?g_noattract=1&g_nostun=1')
        p.evaluate('async () => { await window.__PIXEL_READY__; }')
        p.evaluate(LIVE)
    host.wait_for_timeout(600)
    host.evaluate("window.__SCREENS__.openHostLobby()")
    guest.evaluate("window.__SCREENS__.openJoinLobby()")
    host.wait_for_function("window.__APP__.ui.rects.some((r) => r.id === 'code')", timeout=10000)
    host.evaluate("window.__APP__.ui.focus = 'code'"); host.wait_for_timeout(200)
    host.bring_to_front(); host.keyboard.press('Enter')
    host.wait_for_function("document.querySelectorAll('#g-codebox').length === 2", timeout=30000)
    code = host.evaluate("document.querySelector('#g-codebox textarea').value")
    s.ok(len(code) > 100 and 'KEYBOARD NEEDED' in host.evaluate("document.querySelector('#g-codebox').innerText"), f'the host gets a code to send, labelled ({len(code)} characters)')
    guest.bring_to_front()
    guest.wait_for_function("window.__APP__.ui.rects.some((r) => r.id === 'paste')", timeout=10000)
    guest.evaluate("window.__APP__.ui.focus = 'paste'"); guest.wait_for_timeout(200)
    guest.keyboard.press('Enter')
    guest.wait_for_selector('#g-codebox textarea', timeout=10000)
    guest.fill('#g-codebox textarea', code)
    guest.click('#g-codebox button')
    guest.wait_for_function("document.querySelector('#g-codebox textarea')?.readOnly === true", timeout=30000)
    answer = guest.evaluate("document.querySelector('#g-codebox textarea').value")
    s.ok(len(answer) > 100, f'the guest gets an answer to send back ({len(answer)} characters)')
    host.bring_to_front()
    boxes = host.query_selector_all('#g-codebox')
    boxes[-1].query_selector('textarea').fill(answer)
    boxes[-1].query_selector('button').click()
    host.wait_for_function("window.__APP__.top.session.players.length === 2", timeout=30000)
    s.ok(True, 'pasting it fills the seat')
    # ---- Then the guest's tab closes: the host carries on. ----
    host.evaluate("window.__APP__.top.start()")
    host.wait_for_function('() => window.__GAME__?.name === "area:shift" && window.__GAME__.session.time() > 0', timeout=90000)
    guest.wait_for_function('() => window.__GAME__?.name === "area:shift" && window.__GAME__.session.time() > 0', timeout=90000)
    s.ok(host.evaluate("document.querySelectorAll('#g-codebox').length") == 0, 'the code boxes go when the shift starts')
    guest.close()
    host.wait_for_function("() => { const r = window.__GAME__.remotes.get(1); return r && r.gone; }", timeout=30000)
    s.ok(host.evaluate("window.__GAME__.name") == 'area:shift' and host.evaluate("window.__APP__.top?.name ?? null") != 'results', 'a guest who goes is dropped, and the shift goes on')
    s.ok(errs == [], f'codes: no errors {errs[:2]}')
    ctx.close()

    # ---- The host's tab closes: the guest gets a clean way back. ----
    ctx = b.new_context(viewport={'width': 640, 'height': 360})
    host = ctx.new_page(); guest = ctx.new_page(); errs = []
    for p in (host, guest):
        p.on('pageerror', lambda e: errs.append(str(e)))
        p.goto(DELIVERABLE.as_uri() + '?g_noattract=1')
        p.evaluate('async () => { await window.__PIXEL_READY__; }')
        p.evaluate(LIVE)
    host.wait_for_timeout(600)
    host.evaluate("window.__SCREENS__.openHostLobby()")
    guest.evaluate("window.__SCREENS__.openJoinLobby()")
    pid = guest.wait_for_function("() => { const r = window.__APP__.ui.rects.find((k) => k.id.startsWith('hp')); return r ? r.id.slice(1) : null; }", timeout=30000).json_value()
    guest.evaluate("(pid) => window.__APP__.top.joinHost(pid)", pid)
    host.wait_for_function("window.__APP__.top.session.players.length === 2", timeout=30000)
    host.evaluate("window.__APP__.top.start()")
    guest.wait_for_function('() => window.__GAME__?.name === "area:shift" && window.__GAME__.session.time() > 0', timeout=90000)
    host.close()
    guest.wait_for_function("window.__APP__.top?.name === 'results'", timeout=30000)
    s.ok(guest.evaluate("window.__GAME__.overReason") == 'host-left', 'a guest whose host goes is told so')
    guest.wait_for_timeout(500)
    guest.keyboard.press('Enter')
    guest.wait_for_function("window.__GAME__?.name === 'title' || window.__APP__.top?.name !== 'results'", timeout=60000)
    s.ok(True, 'and gets back to the menus')
    s.ok(errs == [], f'host gone: no errors {errs[:2]}')
    ctx.close()
    b.close()
s.done()
