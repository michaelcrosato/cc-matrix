// Bundles src/*.js (one IIFE), the engine and the AI Hub client into ONE html file in the folder above.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const here = dirname(fileURLToPath(import.meta.url));
const NAME = 'MadMugs-MadMen-claude-sonnet-5-5-medium-20261102-184717';
const ei = JSON.parse(readFileSync(join(here, '..', 'exit-interview.json'), 'utf8'));
writeFileSync(join(here, 'src', '05-feedback.js'), '// generated by build.mjs from exit-interview.json\nconst FEEDBACK = ' + JSON.stringify({ testing: ei.testingFeedback, engine: ei.engineFeedback, prompt: ei.promptFeedback }) + ';\n');
const files = readdirSync(join(here, 'src')).filter(f => f.endsWith('.js')).sort();
const game = files.map(f => readFileSync(join(here, 'src', f), 'utf8')).join('\n');
writeFileSync(join(here, 'game.js'), game);
const engine = readFileSync(join(here, 'vendor/my-3d2dge.js'), 'utf8');
const session = readFileSync(join(here, 'vendor/session.js'), 'utf8');
for (const [n, s] of [['engine', engine], ['game', game], ['session', session]]) if (/<\/script/i.test(s)) throw new Error(n + ' contains </script');
const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<script>${session}</script>
<meta name="hub:session" content="1">
<meta name="hub:session-players" content="1-4">
<meta name="hub:session-mode" content="parallel">
<meta name="hub:session-goal" content="Win the Bellwether Lager account: collect what Garland wants, write the line, then pitch it. Highest standing wins.">
<meta name="hub:session-howto" content="Left stick or WASD walk; ✕ or E talk and use; □ or N notebook; △ or V change view; mouse: click to walk and talk">
<meta name="hub:session-minutes" content="12">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>MAD MUGS: a Mad Men spiritual successor</title>
<style>html, body { margin: 0; height: 100%; background: #000; overflow: hidden } #screen { width: 100%; height: 100%; display: block; image-rendering: pixelated; touch-action: none }</style>
</head>
<body>
<div id="e3-boot" role="status" style="position:fixed;inset:0;z-index:40;display:flex;flex-direction:column;justify-content:flex-end;gap:6px;padding:20px;background:#0c0814;color:#c8b8a0;font:12px/1.5 ui-monospace,Menlo,Consolas,monospace"><style>@keyframes e3-run{from{transform:translateX(-100%)}to{transform:translateX(340%)}}@keyframes e3-late{to{opacity:1}}</style><b style="color:#fff0d0;font-size:16px;letter-spacing:.08em">MAD MUGS</b><span>Pouring the first drink of the day...</span><span style="display:block;height:4px;max-width:440px;overflow:hidden;background:#ffffff14"><span style="display:block;width:30%;height:100%;background:#d9a85c;animation:e3-run 1.2s ease-in-out infinite"></span></span><span style="opacity:0;animation:e3-late .3s 12s forwards">Still starting. If this stays, the game's script did not run: reload, or open the browser's console.</span></div>
<canvas id="screen"></canvas>
<script>${engine}</script>
<script>${game}</script>
</body>
</html>
`;
writeFileSync(join(here, '..', NAME + '.html'), html);
console.log('built', NAME + '.html', (html.length / 1024).toFixed(0) + ' KB');
