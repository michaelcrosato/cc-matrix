"""Shipped single-file interaction, control, lifecycle and campaign checks."""
import json
from pathlib import Path
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parent
failures=[]
checks=0

def check(ok,label):
 global checks
 checks+=1
 if not ok:
  failures.append(label)
  print('FAIL:',label)

PAD="""window.testPads=[];navigator.getGamepads=()=>window.testPads;
window.pad=(i,buttons=[],axes=[0,0,0,0])=>{window.testPads[i]={id:'Synthetic standard pad',index:i,connected:true,mapping:'standard',axes,buttons:Array.from({length:17},(_,n)=>({pressed:buttons.includes(n),value:buttons.includes(n)?1:0,touched:buttons.includes(n)})),timestamp:performance.now()};};"""
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,args=['--enable-unsafe-webgpu','--enable-features=Vulkan','--use-angle=swiftshader','--disable-vulkan-surface'])
 ctx=browser.new_context(viewport={'width':1280,'height':800})
 ctx.add_init_script(PAD)
 page=ctx.new_page()
 errors=[]
 page.on('pageerror',lambda e: errors.append(str(e)))
 page.goto((ROOT.parent/(ROOT.name+'.html')).as_uri())
 page.wait_for_function('!!window.__game',timeout=60000)
 check(page.title().startswith('Ka-Splat!'),'correct self-contained file loaded')
 page.wait_for_function('__game.scene.renderer.info.render.drawCalls>100',timeout=60000)
 check(page.evaluate('__game.state.backend==="WebGPU"&&!__game.scene.renderer._isDeviceLost'),'WebGPU renders the full scene without device loss')
 check(page.evaluate('__game.audio.musicVolume===.1'),'music defaults to ten percent')
 check(page.evaluate('__game.state.screen==="title"'),'title starts ready')
 check(page.evaluate('document.activeElement.dataset.action==="play"'),'title has controller focus')
 page.keyboard.press('Enter')
 page.wait_for_function('__game.state.screen==="playing"')
 check(True,'keyboard confirm starts show')
 page.mouse.move(500,500)
 page.wait_for_function('document.getElementById("splash-label").textContent.includes("Click")')
 check(True,'mouse input displays native click prompt')
 page.evaluate('__game.advance(2.5,false)')
 page.keyboard.down('d')
 page.wait_for_function('__game.model.players[0].x>1',timeout=30000)
 page.keyboard.up('d')
 check(page.evaluate('__game.model.players[0].x>1'),'keyboard moves buckets')
 page.keyboard.press('Space')
 page.wait_for_function('__game.model.stats.splashes===1')
 check(page.evaluate('__game.model.charge<1'),'Space fires and spends splash charge')
 page.keyboard.press('Escape')
 page.wait_for_function('__game.state.screen==="pause"')
 before=page.evaluate('__game.model.time')
 page.wait_for_timeout(200)
 check(page.evaluate('__game.model.time')==before,'pause freezes simulation')
 page.locator('[data-action=dev]').click()
 check(page.evaluate('__game.state.screen==="dev"'),'developer tools reachable through pause')
 page.locator('[data-dev=bucketWidth]').fill('2.7')
 check(page.evaluate('__game.model.config.bucketWidth===2.7'),'live balance slider applies')
 before=page.evaluate('__game.model.time')
 page.locator('[data-action=step]').click()
 after=page.evaluate('__game.model.time')
 check(abs(after-before-1/120)<1e-6,'single physics step advances one tick')
 page.locator('[data-action=debug]').click()
 page.wait_for_function('__game.scene.physicsLines!==null && __game.scene.physicsLines!==undefined')
 check(page.evaluate('__game.state.debug'),'physics display toggle draws debug geometry')
 page.locator('[data-action=reset-dev]').click()
 check(page.evaluate('__game.model.config.bucketWidth===1.6&&!__game.model.config.invincible'),'reset restores balance defaults')
 page.locator('[data-action=resume]').click()
 page.evaluate('pad(0,[],[1,0,0,0])')
 page.wait_for_function('__game.state.lastInput==="pad"',timeout=30000)
 page.evaluate('pad(0)')
 check(page.evaluate('__game.state.lastInput==="pad"'),'standard gamepad selects controller prompts')
 check('✕' in page.locator('#splash-label').inner_text(),'PlayStation splash glyph shown')
 page.evaluate('pad(0,[9])')
 page.wait_for_function('__game.state.screen==="pause"')
 page.evaluate('pad(0)')
 check(True,'Options pauses with synthetic controller')
 page.locator('[data-action=settings]').click()
 page.locator('[data-action=glyphs]').click()
 check('Xbox' in page.locator('[data-action=glyphs]').inner_text(),'Xbox glyph preference toggles')
 page.locator('[data-action=back]').click()
 page.locator('[data-action=about]').click()
 text=page.locator('.credits').inner_text()
 check(all(h in text for h in ['Source Information','Testing Feedback','Engine Feedback','Prompt Feedback']),'all required credits and feedback included')
 page.locator('[data-action=back]').click()
 page.locator('[data-action=quit]').click()
 page.wait_for_timeout(10100)
 page.wait_for_function('__game.state.attract',timeout=3000)
 check(page.evaluate('__game.state.snapshot.attract&&__game.state.snapshot.time>0'),'ten-second idle starts AI attract mode')
 page.keyboard.press('x')
 check(page.evaluate('!__game.state.attract&&__game.state.screen==="title"'),'any input exits attract to title')
 page.evaluate('__game.start({coop:true})')
 check(page.evaluate('__game.model.players.length===2'),'couch co-op creates two catchers')
 page.keyboard.down('l')
 page.wait_for_function('__game.model.players[1].x>3',timeout=30000)
 page.keyboard.up('l')
 check(page.evaluate('__game.model.players[1].x>3'),'P2 keyboard moves second catcher')
 page.evaluate('''()=>{__game.start({coop:false});const cb=__game.model.onEvent;__game.model.onEvent=e=>{if(e.type==='win')cb(e)};__game.advance(180,true);__game.model.onEvent=cb;}''')
 page.wait_for_function('__game.state.screen==="results"')
 stats=page.evaluate('__game.state.snapshot')
 check(stats['phase']=='won' and stats['stats']['waves']==8,'complete eight-wave browser playthrough reaches victory')
 check(stats['stats']['golden']>0 and stats['stats']['caught']>=150,'playthrough exercises gold, gust and all bomb patterns')
 check(page.evaluate('__game.state.best')>=stats['score'],'best score persists after win')
 page.locator('[data-action=restart]').click()
 page.evaluate('__game.advance(2.5,false);__game.model.miss();__game.advance(1.5,false);__game.model.miss();__game.advance(1.5,false);__game.model.miss()')
 page.wait_for_function('__game.state.screen==="results"')
 check(page.evaluate('__game.model.phase==="lost"&&__game.model.lives===0'),'three misses reach complete game-over flow')
 page.evaluate('__game.scene.renderer.backend.device.destroy()')
 page.wait_for_function('__game.scene.recoveryCount===1 && __game.scene.renderer.info.render.drawCalls>100',timeout=60000)
 check(page.evaluate('__game.state.backend==="WebGL 2 fallback"&&document.getElementById("game")===__game.scene.canvas'),'lost graphics device recovers to a fresh working canvas')
 check(not errors,'no browser page errors: '+str(errors))
 ctx.close()
 # Touch is a separate device context using the same browser.
 touch=browser.new_context(viewport={'width':844,'height':390},is_mobile=True,has_touch=True,device_scale_factor=1)
 page=touch.new_page()
 page.goto((ROOT.parent/(ROOT.name+'.html')).as_uri())
 page.wait_for_function('!!window.__game',timeout=60000)
 page.get_by_role('button',name='Let’s make a splash').tap()
 page.evaluate('__game.advance(2.5,false)')
 page.touchscreen.tap(600,250)
 page.wait_for_function('__game.model.stats.splashes>0',timeout=30000)
 check(page.evaluate('__game.state.lastInput==="touch"&&document.body.classList.contains("touch")'),'touch switches to clear minimal control layout')
 check(page.evaluate('__game.model.stats.splashes>0'),'touch tap activates splash')
 check(page.evaluate('getComputedStyle(document.getElementById("move-prompt")).display==="none"'),'touch hides keyboard hints')
 check(page.evaluate('document.documentElement.scrollWidth===innerWidth'),'touch landscape has no horizontal overflow')
 touch.close()
 browser.close()
(ROOT/'ui-test-results.json').write_text(json.dumps({'checks':checks,'failures':failures,'campaign':stats['stats']},indent=2))
print(f'{checks-len(failures)}/{checks} UI checks passed')
raise SystemExit(bool(failures))
