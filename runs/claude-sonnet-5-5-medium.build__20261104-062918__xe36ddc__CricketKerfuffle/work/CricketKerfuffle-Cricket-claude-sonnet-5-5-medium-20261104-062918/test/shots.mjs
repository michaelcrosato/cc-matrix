import { chromium } from 'playwright';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { mkdirSync } from 'node:fs';
const file = resolve(process.argv[2] || 'CricketKerfuffle-Cricket-claude-sonnet-5-5-medium-20261104-062918.html');
mkdirSync('shots', { recursive: true });
const browser = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required', '--use-gl=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errs = [];
page.on('pageerror', e => errs.push(String(e.stack || e)));
page.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
await page.goto(pathToFileURL(file).href);
await page.waitForTimeout(2500);
await page.screenshot({ path: 'shots/01-title.png' });
const run = (js) => page.evaluate(js);
// go to a quick match
await run(`My3D2dge.current.debug.startMatch({mode:'quick',overs:1,wickets:2,diff:1,opp:'witt',ground:'green',chaos:'all',seed:5})`);
await page.waitForTimeout(3500);
await page.screenshot({ path: 'shots/02-intro.png' });
await page.waitForTimeout(3000);
await page.screenshot({ path: 'shots/03-flight.png' });
await page.keyboard.press('KeyJ');
await page.waitForTimeout(700);
await page.screenshot({ path: 'shots/04-hit.png' });
await page.waitForTimeout(1500);
await page.screenshot({ path: 'shots/05-wide.png' });
console.log(await run(`JSON.stringify(My3D2dge.current.debug.snapshot())`));
console.log(errs.length ? errs.slice(0, 5).join('\n---\n') : 'no page errors');
await browser.close();
