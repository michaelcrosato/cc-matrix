import { chromium } from 'playwright';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
const file = resolve(process.argv[2]);
const browser = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errs = []; page.on('pageerror', e => errs.push(String(e.stack || e)));
await page.goto(pathToFileURL(file).href); await page.waitForTimeout(1500);
const ev = js => page.evaluate(js), G = 'My3D2dge.current';
await ev(`${G}.debug.startMatch({mode:'quick',overs:2,wickets:3,diff:1,opp:'gumb',ground:'cow',chaos:'all',seed:31,batFirst:1})`);
const ph = async () => ev(`(()=>{const M=${G}.debug.match();return M?M.ph:'none'})()`);
for (let i = 0; i < 400 && (await ph()) !== 'setup'; i++) await page.waitForTimeout(50);
await page.waitForTimeout(400); await page.screenshot({ path: 'shots/c-setup.png' });
await ev(`${G}.input.press('KeyJ'); setTimeout(()=>${G}.input.release('KeyJ'),50)`); await page.waitForTimeout(700); await page.screenshot({ path: 'shots/c-meter.png' });
await page.waitForTimeout(2200); await page.screenshot({ path: 'shots/c-after.png' });
await ev(`${G}.debug.match().cow = {x:610,y:560,vx:0,vy:0,tx:600,ty:500,mood:0,stopped:0,moo:1}`);
await page.waitForTimeout(400); await page.screenshot({ path: 'shots/c-cow.png' });
console.log(errs.join('\n') || 'no errors');
await browser.close();
