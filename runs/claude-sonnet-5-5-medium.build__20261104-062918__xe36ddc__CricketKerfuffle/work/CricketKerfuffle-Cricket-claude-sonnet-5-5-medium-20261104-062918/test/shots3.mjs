import { chromium } from 'playwright';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
const file = resolve(process.argv[2]);
const browser = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errs = []; page.on('pageerror', e => errs.push(String(e.stack || e))); page.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
await page.goto(pathToFileURL(file).href); await page.waitForTimeout(1800);
const ev = js => page.evaluate(js), G = 'My3D2dge.current';
const shot = async n => { await page.waitForTimeout(900); await page.screenshot({ path: `shots/s-${n}.png` }); };
await ev(`${G}.go('setup')`); await shot('setup');
await ev(`${G}.go('story')`); await shot('story');
await ev(`${G}.debug.startMatch({mode:'story',ch:0,opp:'witt',ground:'green',overs:1,wickets:2,diff:0,chaos:'all',batFirst:1,seed:3})`);
await page.waitForTimeout(3500);
await page.keyboard.press('KeyJ'); await page.waitForTimeout(1500); await page.screenshot({ path: 'shots/s-bowl-setup.png' });
await page.keyboard.press('KeyJ'); await page.waitForTimeout(800); await page.screenshot({ path: 'shots/s-bowl-meter.png' });
await ev(`${G}.debug.devOpen()`); await page.waitForTimeout(600); await page.screenshot({ path: 'shots/s-dev.png' });
await ev(`${G}.go('howto')`); await shot('howto');
await ev(`${G}.go('about')`); await shot('about');
await ev(`${G}.go('cutscene', {lines:${G}.debug.CHAPTERS[0].intro, title:'CHAPTER 1', onDone(){}})`); await page.waitForTimeout(2500); await page.screenshot({ path: 'shots/s-cut.png' });
await ev(`${G}.go('results', {mode:'quick', result:{winner:0, margin:'by 2 wickets'}, sides:[{team:'kerf',score:34,wkts:1,balls:12,fours:3,sixes:2},{team:'witt',score:31,wkts:3,balls:12,fours:2,sixes:1}], data:{}, single:false, ch:0})`); await shot('results');
console.log(errs.length ? errs.slice(0, 4).join('\n') : 'no errors');
await browser.close();
