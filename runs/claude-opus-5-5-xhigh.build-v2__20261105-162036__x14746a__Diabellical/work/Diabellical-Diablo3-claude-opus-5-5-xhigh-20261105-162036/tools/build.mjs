#!/usr/bin/env node
// Bundles the game into one HTML file at the run's root. Generates the About data first.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const dev = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const stem = dev.split('/').pop();
const rootDir = resolve(dev, '..');
const out = join(rootDir, `${stem}.html`);

// About data: one source of truth, the exit interview.
const interviewPath = join(rootDir, 'exit-interview.json');
const fallback = join(dev, 'tools', 'exit-interview.draft.json');
const interview = JSON.parse(readFileSync(existsSync(interviewPath) ? interviewPath : fallback, 'utf8'));
const credits = readFileSync(join(dev, 'CREDITS.md'), 'utf8');
writeFileSync(join(dev, 'src/data/about.generated.js'),
  `// Generated by tools/build.mjs from exit-interview.json and CREDITS.md. Do not edit.\nexport const INTERVIEW = ${JSON.stringify(interview, null, 1)};\nexport const KIT_CREDITS = ${JSON.stringify(credits)};\n`);

mkdirSync(join(dev, '.build'), { recursive: true });
const bundlePath = join(dev, '.build/game.bundle.js');
execFileSync('esbuild', ['game.js', '--bundle', '--format=esm', '--target=es2022', '--charset=utf8', '--legal-comments=none', `--outfile=${bundlePath}`, '--log-level=warning'], { cwd: dev, stdio: 'inherit' });
const bundle = readFileSync(bundlePath, 'utf8').replace(/<\/script/gi, '<\\/script');
const session = readFileSync(join(dev, 'session.js'), 'utf8');

const metas = {
  'hub:session': '1',
  'hub:session-players': '1-4',
  'hub:session-mode': 'shared-world',
  'hub:session-minutes': '8',
  'hub:session-goal': 'Fill the Knell, then slay its Warden together',
  'hub:session-howto': 'Move: stick or WASD. Attack: Cross or click. Skills: face buttons or 1-4.',
  'hub:webgpu': 'required',
};
const metaHtml = Object.entries(metas).map(([k, v]) => `<meta name="${k}" content="${v}">`).join('\n');
const title = /TITLE = '([^']+)'/.exec(readFileSync(join(dev, 'src/data/meta.js'), 'utf8'))[1];
const parts = [
  '<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n<script>',
  session,
  `</script>\n${metaHtml}\n<title>${title}</title>\n<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover">\n<link rel="icon" href="data:,">\n<style>html,body{margin:0;height:100%;background:#0d0b14}#app{position:fixed;inset:0}</style>\n</head>\n<body>\n<div id="app"></div>\n<script type="module">\n`,
  bundle,
  '\n</script>\n</body>\n</html>\n',
];
writeFileSync(out, parts.join(''));
const dest = join(dev, 'index.html');
if (!process.argv.includes('--quiet')) console.log(`built ${out} (${(parts.join('').length / 1048576).toFixed(2)} MB)`);
