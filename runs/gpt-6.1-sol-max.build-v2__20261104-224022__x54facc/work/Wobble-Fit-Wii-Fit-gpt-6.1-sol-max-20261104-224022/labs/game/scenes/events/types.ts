/** @file Shared activity contract and serializable round state. */
import type { Lean, Wobble, WobbleConfig } from '../wobble';
import type { EventId } from '../data/days';
export type Marble = { x: number; y: number; vx: number; vy: number; sunk: boolean };
export type ActivityRun = {
  id: EventId;
  tick: number;
  length: number;
  score: number;
  total: number;
  samples: number;
  count: number;
  combo: number;
  bestCombo: number;
  mistakes: number;
  lastFoot: number;
  lastTap: number;
  lastL: boolean;
  lastR: boolean;
  composure: number;
  progress: number;
  hold: number;
  phase: number;
  pose: number;
  breath: number;
  targetX: number;
  targetY: number;
  ring: number;
  angle: number;
  previousAngle: number;
  velocity: number;
  offset: number;
  gate: number;
  marbles: Marble[];
  tray: number;
  sunk: number;
  guests: number;
  tilt: number;
  scores: number[];
  seats: Wobble[];
  inputs: (Lean | null)[];
  seed: number;
  short: boolean;
  children: ActivityRun[];
};
export type EventConfig = {
  wobble: WobbleConfig;
  get: (key: string) => number;
  auto: boolean;
  day: number;
  expert: boolean;
};
export type Guide = {
  x: number;
  y: number;
  ring: number;
  title: string;
  instruction: string;
  pose: string;
  foot: number;
};
export type ActivityModule = {
  id: EventId;
  setup: (run: ActivityRun) => void;
  guide: (run: ActivityRun, cfg: EventConfig) => Guide;
  step: (run: ActivityRun, wobble: Wobble, input: Lean, cfg: EventConfig) => void;
  score: (run: ActivityRun, wobble: Wobble) => number;
  bot: (run: ActivityRun, wobble: Wobble, cfg: EventConfig, kind: string) => Lean;
  teardown: (run: ActivityRun) => void;
};
