import { readFileSync, writeFileSync } from 'node:fs';
// Builds the single-file game and the exit interview. Run from anywhere: node build/build.mjs
// 1. writes src/05-feedback.js from build/feedback.json (the About screen reads it)
// 2. checks the source for banned words and calls (TODO, placeholders, Math.random, network and dialogs)
// 3. bundles hub/session.js (first script, right after <meta charset>), the engine and src/ in manifest order into one HTML
// 4. writes exit-interview.json beside it, and checks that it parses and answers every field
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rd = f => readFileSync(path.join(root, f), 'utf8');
const manifest = JSON.parse(rd('build/manifest.json'));
const feedback = JSON.parse(rd('build/feedback.json'));
const fail = msg => { console.error('BUILD FAILED: ' + msg); process.exit(1); };

writeFileSync(path.join(root, 'src/05-feedback.js'),
  '// generated by build/build.mjs from build/feedback.json: the About & Credits screen reads these\n' +
  'const FEEDBACK = ' + JSON.stringify(feedback, null, 1) + ';\n');

const banned = [/\bTODO\b/, /\bFIXME\b/, /\bXXX\b/, /placeholder/i, /\blorem\b/i, /Math\.random/, /\bfetch\(/, /WebSocket/, /RTCPeerConnection/, /\balert\(/, /\bconfirm\(/, /\bprompt\(/, /window\.open/];
const srcFiles = manifest.order.map(f => ({ f, text: rd('src/' + f) }));
for (const { f, text } of srcFiles) for (const re of banned) if (re.test(text)) fail(`${f} contains ${re}`);

const session = rd(manifest.hub);
const engine = rd(manifest.engine);
const hubMeta = {
  'hub:session': '1', 'hub:session-players': '1-4', 'hub:session-mode': 'ghost', 'hub:session-minutes': '3',
  'hub:session-goal': 'Most points in three minutes wins. Bucks only, never does!',
  'hub:session-howto': 'Aim: mouse or left stick. Shoot: click or R2. Pump: R or Square.',
};
if (hubMeta['hub:session-goal'].length > 60) fail('goal over 60 characters');
if (hubMeta['hub:session-howto'].length > 80) fail('howto over 80 characters');
const metas = Object.entries(hubMeta).map(([k, v]) => `<meta name="${k}" content="${v.replace(/"/g, '&quot;')}">`).join('\n');

const body = srcFiles.map(({ text }) => text).join('\n');
const html = `<!doctype html><html lang="en"><head>
<meta charset="utf-8">
<script>${session}</script>
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>${manifest.title}</title>
${metas}
<style>html,body{margin:0;height:100%;background:#000;overflow:hidden}#screen{width:100%;height:100%;display:block;image-rendering:pixelated;touch-action:none}</style>
</head><body>
<div id="e3-boot" role="status" style="position:fixed;inset:0;z-index:40;display:flex;flex-direction:column;justify-content:flex-end;gap:6px;padding:20px;background:#05040a;color:#a9a1c8;font:12px/1.5 ui-monospace,Menlo,Consolas,monospace"><b style="color:#f4f0ff;font-size:16px;letter-spacing:.08em">${manifest.title.toUpperCase()}</b><span>Starting · my-3D2dge v0.85.2</span><span>If this stays, reload the page or open the browser console.</span></div>
<canvas id="screen"></canvas>
<script>${engine}</script>
<script>(() => {
${body}
})();</script>
</body></html>
`;
writeFileSync(path.join(root, manifest.bundle), html);

// the exit interview: the same answers as the About screen, in the shape the tools read
const ex = {
  sourceInformation: feedback.sourceInformation,
  testingFeedback: feedback.testingFeedback,
  engineFeedback: feedback.engineFeedback,
  promptFeedback: feedback.promptFeedback,
  aiHub: feedback.aiHub,
};
writeFileSync(path.join(root, manifest.exitInterview), JSON.stringify(ex, null, 2) + '\n');
console.log('built', path.basename(manifest.bundle), (html.length / 1024).toFixed(0) + ' KB');
