(function (root) {
  const A = root.ABJ, E = root.My3D2dge;
  const colors = ['#a5e96d', '#ffb16d', '#c99bff', '#6edce5'];
  const shapes = [
    ['....33...33....','.....33333.....','...334444433...','..34444444443..','.3444e444e4443.','33444e444e44433','334444444444433','..33333333333..','...33.333.33...','..33..3.3..33..','.33.........33.'],
    ['......333......','....3344433....','...344444443...','..34444444443..','.344ee444ee443.','.344ee444ee443.','.3444444444443.','..33444444433..','...333333333...','..33..3.3..33..','...3..3.3..3...'],
    ['..33.......33..','...33.....33...','....3333333....','...344444443...','..34e44444e43..','.334ee444ee433.','334444444444433','.3333333333333.','...33.333.33...','..33..3.3..33..','..3.........3..'],
    ['.....33333.....','...334444433...','..34444444443..','.3444eeeee4443.','33444eeeee44433','334444444444433','.3344444444433.','...333333333...','..33..333..33..','.33..33.33..33.','..3..3...3..3..']
  ];
  function make(rows, color, scale = 1) {
    const t = E.tones(color);
    const grid = Array.from({ length: rows.length + 2 }, () => Array(Math.max(...rows.map(r => r.length)) + 2).fill('.'));
    rows.forEach((row, y) => [...row].forEach((ch, x) => { if (ch !== '.' && ch !== ' ') for (let dy = 0; dy < 3; dy++) for (let dx = 0; dx < 3; dx++) grid[y + dy][x + dx] = '1'; }));
    rows.forEach((row, y) => [...row].forEach((ch, x) => { if (ch !== '.' && ch !== ' ') grid[y + 1][x + 1] = ch; }));
    return E.sprite(grid.map(row => row.join('')), { '1': t.deep, '2': t.sh, '3': t.base, '4': t.lt, '5': t.hi, e: '#152239', w: '#fff5d6', y: '#ffd36a', r: '#fa6e77', b: '#75e6ff' }, scale);
  }
  const enemies = shapes.map((rows, i) => {
    // Body underside shaded per row; the march pose swaps feet on the beat.
    const shaded = rows.map((r, y) => y > 6 ? r.replace(/4/g, '3').replace(/3/g, y > 8 ? '2' : '3') : r);
    const alt = shaded.map((r, y) => y > 7 ? r.split('').reverse().join('').replace(/^\./, '3').replace(/3$/, '.') : r);
    return E.anim([make(shaded, colors[i]), make(alt, colors[i])], 1, { loop: true });
  });
  const cannonRows = ['.........b.........','.........b.........','........bwb........','........353........','.....333444333.....','....34444444443....','...34444ee444443...','..344444ee4444443..','.3344444444444433.','3344444444444444433','3333333333333333333','.2222222222222222.','..22.22.22.22.22...'];
  A.art = {
    enemies,
    cannons: [make(cannonRows, '#64ead5'), make(cannonRows, '#ffa285')],
    saucer: E.anim([
      make(['........555........','.....334444433.....','....3444www4443....','...344wwwww44443...','.33444444444444433.','33444y44y44y44y4433','..233333333333332..','....22.22.22.22....'], '#f594cf'),
      make(['........555........','.....334444433.....','....3444www4443....','...344wwwww44443...','.33444444444444433.','3344y44y44y44y44433','..233333333333332..','.....22.22.22.....'], '#f594cf')
    ], 4),
    shell: make(['.....55555.....','...554444455...','..54444444445..','.5443333333445.','544333333333445','5433.......3345','543.........345','.43.........34.'], '#6dc6fa'),
    bomb: E.anim([make(['..r..','.ryr.','.rwr.','..y..','..r..','..r..'], '#f4926c'), make(['..y..','.ryr.','.rwr.','..r..','..y..','..r..'], '#f4926c')], 8),
    salvage: E.anim([make(['...y...','..ywy..','.yw4wy.','yw444wy','.yw4wy.','..ywy..','...y...'], '#ffc45b'), make(['...y...','..ywy..','..y4y..','..444..','..y4y..','..ywy..','...y...'], '#ffc45b')], 5)
  };
  A.colorRows = colors;
})(globalThis);
