def touch_profiles(p, browser, check, snap, choose, evidence, url):
    for device in ['iPhone 13','iPad (gen 7)']:
        context=browser.new_context(**p.devices[device])
        page=context.new_page();page.goto(url)
        page.wait_for_function('window.__game?.app.screen==="title"')
        choose(page,'SOLO DEFENSE',True)
        rows=page.evaluate('''()=>{const c=document.querySelector('canvas').getBoundingClientRect();return __game.game.debug.snapshot().rows.map(r=>r.box.h/__game.game.H*c.height)}''')
        check(device+' has thumb-sized portrait menu targets', min(rows)>=40, rows)
        choose(page,'CONTROLS & DEPLOY',True)
        page.screenshot(path=str(evidence/('touch-controls-'+device.split()[0]+'.png')))
        choose(page,'DEPLOY CANNONS',True)
        page.wait_for_function('__game.app.sim.s.tick>300')
        page.evaluate('''()=>{const c=document.querySelector('canvas'),b=c.getBoundingClientRect();window.touchEv=(kind,id,x,y)=>c.dispatchEvent(new PointerEvent(kind,{pointerId:id,pointerType:'touch',isPrimary:id===1,clientX:b.x+x*b.width,clientY:b.y+y*b.height,bubbles:true,cancelable:true}));touchEv('pointerdown',1,.45,.82);touchEv('pointermove',1,.62,.82);touchEv('pointerdown',2,.7,.8)}''')
        page.wait_for_function('__game.app.sim.s.tutorial.moved && __game.app.sim.s.tutorial.fired')
        check(device+' touch input and thumb-sized menu reach combat', snap(page)['touchContacts']==2 and page.evaluate('(()=>{const c=document.querySelector("canvas").getBoundingClientRect();return __game.app.menuBox.h/__game.game.H*c.height>=44})()'))
        page.wait_for_function('__game.app.sim.s.ships[0].x >= 294')
        page.evaluate("touchEv('pointermove',1,.45,.82)")
        page.wait_for_function('__game.app.canTouchRepair')
        b=page.evaluate('__game.app.repairBox')
        point=page.evaluate('(b)=>{const c=document.querySelector("canvas").getBoundingClientRect();return {x:c.x+(b.x+b.w/2)/__game.game.W*c.width,y:c.y+(b.y+b.h/2)/__game.game.H*c.height}}',b)
        page.touchscreen.tap(point['x'],point['y'])
        page.wait_for_function('__game.app.sim.s.ships[0].repairs>0')
        check(device+' contextual repair spends the held salvage charge', snap(page)['world']['ships'][0]['charges']==0)
        page.evaluate("touchEv('pointercancel',1,.62,.82);touchEv('pointercancel',2,.7,.8)")
        check(device+' touch cancellation releases every contact', snap(page)['touchContacts']==0)
        page.screenshot(path=str(evidence/('portrait-'+device.split()[0]+'.png')))
        page.evaluate('__game.game.stop();__game.game.debug.title();__game.game.advance(10.2)')
        page.touchscreen.tap(20,20);page.evaluate('__game.game.advance(.08)')
        check(device+' touch wake is consumed on title', snap(page)['screen']=='title')
        page.evaluate('__game.game.start()')
        page.wait_for_function('__game.app.uiTime >= (__game.app.wakeGuard || 0)')
        choose(page,'ABOUT / CREDITS',True)
        page.evaluate('__game.app.aboutPage=__game.game.debug.aboutPages().length-1')
        page.set_viewport_size({'width':844,'height':390});page.wait_for_timeout(100)
        check(device+' rotation preserves combat bounds', page.evaluate('ABJ.FIELD.w===480 && ABJ.FIELD.h===270 && __game.app.contacts.size===0'))
        rotation = page.evaluate('({errors:__game.game.errors,page:__game.app.aboutPage,count:__game.game.debug.aboutPages().length,H:__game.game.H,W:__game.game.W,screen:__game.app.screen,guard:__game.app.wakeGuard,ui:__game.app.uiTime})')
        check(device+' credits reflow and native renderer survive rotation', not rotation['errors'] and rotation['page'] < rotation['count'] and rotation['screen']=='about', rotation)
        context.close()


def storage_and_browsers(p, chromium, check, snap, choose, url):
    for mode in ['blocked','malformed']:
        context=chromium.new_context()
        if mode=='blocked':
            context.add_init_script("Object.defineProperty(window,'localStorage',{get(){throw new Error('Storage blocked by test')}})")
        else:
            context.add_init_script("try{localStorage.setItem('settings:astro-battle-jam-v1','{broken');localStorage.setItem('jam-records-v1','{broken')}catch{}")
        page=context.new_page();page.goto(url);page.wait_for_function('window.__game?.app.screen==="title"')
        choose(page,'SOLO DEFENSE');choose(page,'CONTROLS & DEPLOY');choose(page,'DEPLOY CANNONS')
        check(mode+' storage still permits ordinary play', snap(page)['screen']=='play' and snap(page)['settings']['music']==.1)
        context.close()
    for name in ['firefox','webkit']:
        engine=getattr(p,name);browser=engine.launch()
        context=browser.new_context(viewport={'width':1280,'height':720})
        page=context.new_page();errs=[];page.on('pageerror',lambda e:errs.append(str(e)))
        page.goto(url);page.wait_for_function('window.__game?.app.screen==="title"')
        choose(page,'SOLO DEFENSE');choose(page,'CONTROLS & DEPLOY');choose(page,'DEPLOY CANNONS')
        page.keyboard.down('Space');page.keyboard.down('a');page.wait_for_function('__game.app.sim.s.tutorial.fired && __game.app.sim.s.tutorial.moved');page.keyboard.up('Space');page.keyboard.up('a')
        check(name+' export startup, input and layout smoke', not errs and page.evaluate('__game.game.errors.length===0'),errs)
        browser.close()
