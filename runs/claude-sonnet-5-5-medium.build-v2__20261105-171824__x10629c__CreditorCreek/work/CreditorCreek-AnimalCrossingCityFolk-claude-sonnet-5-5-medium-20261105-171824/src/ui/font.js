const cache = new Map();
/** Compose a string into sprite rows (height 9). Returns { rows, w }. */
export function textRows(str) {
  let hit = cache.get(str); if (hit) return hit;
  const rows = ['', '', '', '', '', '', '', '', ''];
  let w = 0;
  for (const ch of str) {
    const g = G[ch] ?? G['?'];
    for (let i = 0; i < 9; i++) rows[i] += g[i] + '.';
    w += g[0].length + 1;
  }
  hit = { rows, w: Math.max(0, w - 1) };
  if (cache.size > 4000) cache.clear();
  cache.set(str, hit);
  return hit;
}
export const textWidth = (s) => textRows(s).w;
export const LINE = 12;
/** Greedy wrap into lines that fit maxW art pixels. */
export function wrapText(str, maxW) {
  const out = [];
  for (const para of String(str).split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const t = line ? line + ' ' + word : word;
      if (textWidth(t) > maxW && line) { out.push(line); line = word; } else line = t;
    }
    out.push(line);
  }
  return out;
}
