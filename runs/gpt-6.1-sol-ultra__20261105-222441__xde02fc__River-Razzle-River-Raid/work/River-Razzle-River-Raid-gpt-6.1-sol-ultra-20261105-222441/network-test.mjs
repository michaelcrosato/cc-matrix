import assert from 'node:assert/strict';
import { Network } from './hub.js';
globalThis.window = { addEventListener() {}, removeEventListener() {} };
globalThis.location = new URL('http://127.0.0.1/river.html');
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
let count = 0;
let failures = 0;
const check = (name, fn) => { count++; try { fn(); } catch(error) { failures++; console.log(`FAIL ${name}: ${error.message}`); } };
const events = { host: [], guest: [] };
const host = new Network({ onInput: (input, from) => events.host.push({input,from}), onLeave: leave => events.host.push({leave}) });
const guest = new Network({ onStart: data => events.guest.push({start:data}), onSnapshot: state => events.guest.push({state}), onEnd: data => events.guest.push({end:data}) });
try {
  await host.init();
  check('solo defaults', () => assert.equal(host.active, false));
  const code = host.createRoom();
  check('room code', () => assert.match(code, /^[A-Z0-9]{4}$/));
  const joined = await guest.joinRoom(code);
  check('guest connected', () => assert.equal(joined, true));
  check('host sees two players', () => assert.equal(host.players.length, 2));
  check('guest seat one', () => assert.equal(guest.localId, 1));
  check('guest cannot start', () => assert.equal(guest.startStandalone(0), false));
  host.startStandalone(0);
  await sleep(50);
  check('guest receives start', () => assert.ok(events.guest.some(e => e.start)));
  host.update(1,{},{score:50,z:12,players:[{x:2}]});
  guest.update(1,{x:7,y:-6,fire:1,pulse:true});
  await sleep(50);
  check('host gets cleaned guest input', () => assert.deepEqual(events.host[0], {input:{x:1,y:-1,fire:true,pulse:true},from:1}));
  check('guest receives host state', () => assert.equal(events.guest.find(e => e.state).state.score,50));
  guest.update(1,{target:4.25});
  await sleep(20);
  check('guest mouse steering reaches host', () => assert.equal(events.host.at(-1).input.target,4.25));
  guest.update(1,{target:999});
  await sleep(20);
  check('guest mouse target clamped safely', () => assert.equal(events.host.at(-1).input.target,80));
  check('traffic in both directions', () => assert.ok(host.sent > 0 && host.received > 0 && guest.sent > 0 && guest.received > 0));
  host.finish(100,true,{Bridges:3});
  await sleep(30);
  check('guest receives team result', () => assert.equal(events.guest.find(e => e.end).end.won,true));
  check('room host ends', () => assert.equal(host.ended,true));
  check('room guest ends', () => assert.equal(guest.ended,true));
  const before = host.sent;
  host.update(1,{},{});
  check('no traffic after end', () => assert.equal(host.sent,before));
  guest.leaveRoom();
  await sleep(30);
  check('guest departure removes host seat', () => assert.equal(host.players.length,1));
  check('host notified of departure', () => assert.equal(events.host.find(e=>e.leave).leave.id,1));
  const nextCode=host.createRoom();
  await guest.joinRoom(nextCode);
  host.startStandalone(0);
  await sleep(20);
  host.leaveRoom();
  await sleep(30);
  check('host departure stops guest', () => assert.ok(!guest.active && !guest.started));
  guest.leaveRoom();
  const handlers = {};
  let ready = 0, result, sends = [];
  window.AIHub = { active:true, time:() => 10, ready:() => ready++, send:(data,opts) => {sends.push({data,opts}); return true;}, finish:data => {result=data;}, connect:async () => ({isHost:true,me:8,host:8,server:true,players:[{id:0,name:'One'},{id:1,name:'Two'}]}), on:(event,fn) => {handlers[event]=fn; return () => {};}};
  const server = new Network();
  await server.init();
  server.ready();
  check('hub ready called', () => assert.equal(ready,1));
  check('nonplayer host supported', () => assert.ok(server.server && server.isHost && !server.players.some(p=>p.id===server.localId)));
  handlers.start({in:0});
  server.update(1,{}, {score:123});
  check('nonplayer host sends state', () => assert.equal(sends[0].data.type,'state'));
  handlers['time-up']({graceMs:100});
  await sleep(35);
  check('time-up returns valid standings', () => assert.deepEqual(result.standings,[[0,1]]));
  check('time-up reports current score', () => assert.deepEqual(result.scores,{0:123,1:123}));
  handlers.end({reason:'finished',standings:[[0,1]]});
  check('hub end freezes network', () => assert.equal(server.ended,true));
  server.destroy();
  const guestHandlers = {};
  let guestSends = [];
  window.AIHub={ active:true,time:()=>20,connect:async()=>({isHost:false,me:1,host:0,server:false,players:[{id:0},{id:1}]}),on:(event,fn)=>{guestHandlers[event]=fn;return ()=>{};},send:(data,opts)=>{guestSends.push({data,opts});return true;}};
  const hubGuest = new Network({onSnapshot: state=>events.guest.push({hubState:state})});
  await hubGuest.init();
  guestHandlers.start({in:0});
  hubGuest.update(1,{x:0.5,fire:true});
  check('hub guest sends only host input',()=>assert.equal(guestSends[0].opts.to,0));
  guestHandlers.message({game:'river-razzle',v:1,type:'state',seq:1,state:{score:444}},0);
  check('hub guest accepts host state',()=>assert.equal(hubGuest.lastSnapshot.score,444));
  guestHandlers.message({game:'river-razzle',v:1,type:'state',seq:2,state:{score:555}},1);
  check('hub guest rejects another guest state',()=>assert.equal(hubGuest.lastSnapshot.score,444));
  guestHandlers.message({game:'river-razzle',v:1,type:'state',seq:0,state:{score:666}},0);
  check('hub guest rejects stale state',()=>assert.equal(hubGuest.lastSnapshot.score,444));
  guestHandlers.end({reason:'host-left'});
  check('hub guest stops on host exit',()=>assert.equal(hubGuest.ended,true));
  hubGuest.destroy();
} catch(error) { failures++; console.log(`FAIL network test crashed: ${error.stack}`); }
finally { host.destroy(); guest.destroy(); }
console.log(`${count} network checks, ${failures} failures`);
if(failures) process.exitCode=1;
