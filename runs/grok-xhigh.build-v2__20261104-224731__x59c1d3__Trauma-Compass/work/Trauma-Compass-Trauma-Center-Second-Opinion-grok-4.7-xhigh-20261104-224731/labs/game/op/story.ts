/**
 * @file The campaign's scenes. Each one is a run of short boxes, twelve to thirty-five, said out loud over captions.
 * A drama box is a snapped close-up and a caption. Nothing here is quoted from another game.
 */
export interface Box {
  who: string;
  text: string;
  /** A huge caption, when this beat is a drama cut. */
  drama?: string;
}

/** One skippable scene. */
export interface Scene {
  id: string;
  where: string;
  boxes: Box[];
}

/** `WHO: line` or `WHO: line :: CAPTION`. */
function boxes(lines: readonly string[]): Box[] {
  return lines.map((line) => {
    const cut = line.indexOf(' :: ');
    const body = cut === -1 ? line : line.slice(0, cut);
    const speaker = body.indexOf(': ');
    return {
      who: body.slice(0, speaker),
      text: body.slice(speaker + 2),
      ...(cut === -1 ? {} : { drama: line.slice(cut + 4) }),
    };
  });
}

