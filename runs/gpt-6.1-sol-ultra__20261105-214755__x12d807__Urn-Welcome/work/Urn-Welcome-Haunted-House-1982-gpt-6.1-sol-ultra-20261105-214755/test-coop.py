"""Real final-game co-op integration, two tabs, one browser."""
from pathlib import Path
from http.server import ThreadingHTTPServer,SimpleHTTPRequestHandler
from functools import partial
import threading
from playwright.sync_api import sync_playwright
root=Path(__file__).resolve().parent.parent
folder=Path(__file__).resolve().parent.name
failures=[];checks=0
class Quiet(SimpleHTTPRequestHandler):
    def log_message(self,*args):pass
def check(ok,label):
    global checks
    checks+=1
    if not ok:failures.append(label)
server=ThreadingHTTPServer(('127.0.0.1',0),partial(Quiet,directory=str(root)))
threading.Thread(target=server.serve_forever,daemon=True).start()
url=f'http://127.0.0.1:{server.server_port}/{folder}.html'
try:
    with sync_playwright() as p:
        browser=p.chromium.launch(headless=True,args=['--enable-unsafe-webgpu','--use-angle=swiftshader','--enable-features=Vulkan','--use-webgpu-adapter=swiftshader'])
        context=browser.new_context(viewport={'width':1280,'height':720})
        host=context.new_page();guest=context.new_page()
        guest.add_init_script('window.__testPad=null;window.__padPolls=0; Object.defineProperty(navigator,"getGamepads",{value:()=>{window.__padPolls++;return window.__testPad?[window.__testPad]:[]},configurable:true});')
        errors=[]
        host.on('pageerror',lambda error:errors.append('host: '+str(error)))
        guest.on('pageerror',lambda error:errors.append('guest: '+str(error)))
        host.goto(url,wait_until='domcontentloaded');guest.goto(url,wait_until='domcontentloaded')
        host.wait_for_function('window.__URN',timeout=60000);guest.wait_for_function('window.__URN',timeout=60000)
        host.evaluate('__URN.action("host")')
        code=host.evaluate('__URN.network.room')
        guest.evaluate('(code)=>__URN.action("join",code)',code)
        host.wait_for_function('__URN.network.connected && __URN.state?.playerCount===2')
        guest.wait_for_function('__URN.network.connected && __URN.state?.playerCount===2')
        check(host.evaluate('__URN.network.role==="host" && __URN.mode==="play"'),'final game host paired')
        check(guest.evaluate('__URN.network.localIndex===1 && __URN.mode==="play"'),'final game guest paired')
        host.evaluate('__URN.tuning.enemy=0; __URN.state.players.forEach(p=>p.invincible=99)')
        def position_guest(x,z):
            host.evaluate('([x,z])=>{__URN.state.players[1].x=x;__URN.state.players[1].z=z;}',[x,z])
            guest.wait_for_function('([x,z])=>Math.hypot(__URN.state.players[1].x-x,__URN.state.players[1].z-z)<.05',arg=[x,z])
        position_guest(-8,4)
        guest.keyboard.press('e')
        host.wait_for_function('__URN.state.players[1].tool==="key"')
        guest.wait_for_function('__URN.state.players[1].tool==="key"')
        check(host.evaluate('__URN.state.players[0].tool===null'),'guest pickup uses guest inventory')
        position_guest(-8,1.2)
        guest.keyboard.press('e')
        host.wait_for_function('__URN.state.doors.some(d=>d.x===-8 && !d.locked)')
        guest.wait_for_function('__URN.state.doors.some(d=>d.x===-8 && !d.locked)')
        check(True,'guest unlock shared door')
        position_guest(-8,-4)
        guest.keyboard.press('e')
        host.wait_for_function('__URN.state.fragments===1');guest.wait_for_function('__URN.state.fragments===1')
        check(True,'guest recovers shared fragment')
        guest.keyboard.press('q')
        host.wait_for_function('__URN.state.players[1].tool===null && __URN.state.items.some(i=>i.type==="key" && !i.taken)')
        guest.wait_for_function('__URN.state.players[1].tool===null && __URN.state.items.some(i=>i.type==="key" && !i.taken)')
        check(True,'guest drops shared tool')
        position_guest(9,5)
        guest.keyboard.press('e')
        host.wait_for_function('__URN.state.floor===1');guest.wait_for_function('__URN.state.floor===1')
        check(host.evaluate('__URN.state.players[0].x===9'),'guest stairs move whole party')
        start=host.evaluate('({x:__URN.state.players[1].x,z:__URN.state.players[1].z})')
        guest.keyboard.down('a')
        host.wait_for_function('(p)=>Math.hypot(__URN.state.players[1].x-p.x,__URN.state.players[1].z-p.z)>.15',arg=start,polling=100)
        guest.keyboard.up('a')
        host.wait_for_function('!__URN.state.players[1].moving',polling=100)
        check(True,'guest continuous movement reaches host')
        p2=host.evaluate('({x:__URN.state.players[1].x,z:__URN.state.players[1].z})')
        start=host.evaluate('({x:__URN.state.players[0].x,z:__URN.state.players[0].z})')
        host.keyboard.down('d')
        host.wait_for_function('(p)=>Math.hypot(__URN.state.players[0].x-p.x,__URN.state.players[0].z-p.z)>.15',arg=start,polling=100)
        host.keyboard.up('d')
        host.wait_for_function('!__URN.state.players[0].moving',polling=100)
        check(host.evaluate('(p)=>Math.hypot(__URN.state.players[0].x-p.x,__URN.state.players[0].z-p.z)>.15',arg=start),'host movement uses host seat')
        check(host.evaluate('(p)=>Math.hypot(__URN.state.players[1].x-p.x,__URN.state.players[1].z-p.z)<.15',p2),'host movement preserves guest seat')
        # Escape and standard-mapping Options each pause only this guest's controls.
        def pad_options(expected_mode):
            guest.evaluate('''()=>{if(!window.__testPad)window.__testPad={id:'Standard test pad',index:0,connected:true,mapping:'standard',axes:[0,0,0,0],buttons:Array.from({length:18},()=>({pressed:false,touched:false,value:0}))};window.__testPad.buttons[9]={pressed:true,touched:true,value:1};}''')
            guest.wait_for_function('(mode)=>__URN.mode===mode && __URN.ui.screen===(mode===\"pause\"?\"pause\":\"none\")',arg=expected_mode,polling=100)
            released_at=guest.evaluate('window.__testPad.buttons[9]={pressed:false,touched:false,value:0};window.__padPolls')
            guest.wait_for_function('(n)=>window.__padPolls>n',arg=released_at,polling=100)
        for pause_method in ['Escape','Options']:
            position_guest(0,5)
            guest_before=host.evaluate('({x:__URN.state.players[1].x,z:__URN.state.players[1].z})')
            guest.keyboard.down('d')
            host.wait_for_function('(p)=>__URN.state.players[1].moving && Math.hypot(__URN.state.players[1].x-p.x,__URN.state.players[1].z-p.z)>.1',arg=guest_before,polling=100)
            if pause_method=='Escape':guest.keyboard.press('Escape')
            else:pad_options('pause')
            guest.wait_for_function('__URN.mode==="pause" && __URN.ui.screen==="pause"',polling=100)
            check(True,pause_method+' opens guest pause menu')
            guest.keyboard.up('d')
            host.wait_for_function('!__URN.state.players[1].moving',polling=100)
            stopped=host.evaluate('({x:__URN.state.players[1].x,z:__URN.state.players[1].z})')
            elapsed=guest.evaluate('__URN.state.elapsed')
            host_before=host.evaluate('({x:__URN.state.players[0].x,z:__URN.state.players[0].z,time:__URN.state.elapsed})')
            host.keyboard.down('a')
            host.wait_for_function('(p)=>__URN.state.elapsed-p.time>.15 && Math.hypot(__URN.state.players[0].x-p.x,__URN.state.players[0].z-p.z)>.1',arg=host_before,polling=100)
            host.keyboard.up('a')
            host.wait_for_function('!__URN.state.players[0].moving',polling=100)
            guest.wait_for_function('(t)=>__URN.state.elapsed-t>.1',arg=elapsed,polling=100)
            check(guest.evaluate('__URN.mode==="pause" && __URN.ui.screen==="pause"'),'guest '+pause_method+' pause survives snapshots')
            check(host.evaluate('(p)=>Math.hypot(__URN.state.players[1].x-p.x,__URN.state.players[1].z-p.z)<.04',stopped),'guest '+pause_method+' pause sends neutral controls')
            check(host.evaluate('(p)=>__URN.state.elapsed-p.time>.15 && Math.hypot(__URN.state.players[0].x-p.x,__URN.state.players[0].z-p.z)>.1',host_before),'host continues while guest '+pause_method+' menu is open')
            check(guest.evaluate('(t)=>__URN.state.elapsed-t>.1',elapsed),'guest '+pause_method+' pause receives live host snapshots')
            if pause_method=='Escape':guest.locator('[data-action=resume]').click()
            else:pad_options('play')
            guest.wait_for_function('__URN.mode==="play" && __URN.ui.screen==="none"',polling=100)
            check(True,'guest '+pause_method+' pause resumes')
        guest.evaluate('window.__testPad=null')
        host.evaluate('__URN.state.fragments=3;__URN.loadFloor(0,{x:0,z:6.5});__URN.interact()')
        host.wait_for_function('__URN.mode==="win"');guest.wait_for_function('__URN.mode==="win"')
        check(True,'co-op victory appears on both copies')
        host.evaluate('__URN.start()')
        guest.wait_for_function('__URN.mode==="play" && __URN.state.fragments===0')
        check(host.evaluate('__URN.state.playerCount===2'),'co-op rematch retains both seats')
        check(not errors,'no game errors: '+'; '.join(errors))
        guest.evaluate('__URN.network.disconnect()')
        host.wait_for_function('__URN.state.playerCount===1',polling=100)
        check(True,'guest departure removes inactive player')
        browser.close()
except Exception as error:failures.append(str(error).split('\n')[0])
finally:server.shutdown();server.server_close()
for failure in failures:print('FAIL '+failure)
print(f'{checks} co-op checks, {len(failures)} failures')
raise SystemExit(bool(failures))
