// The bundler: one self-contained HTML file from index.html (every <script src> inlined, '</script' escaped, session.js
// first in <head> and byte-identical), FF_ABOUT from src/about.json, and exit-interview.json beside the deliverable from
// the same object, so the About screen and the file never disagree. node build.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const here = new URL('./', import.meta.url), R = f => readFileSync(new URL(f, here), 'utf8');
const NAME = 'AmericanFootballFiasco-AmericanFootball-claude-opus-5-5-xhigh-20261104-070229';
const about = JSON.parse(R('src/about.json'));
writeFileSync(new URL('src/about.js', here), '// generated by build.mjs from src/about.json: the About & Credits pages\nwindow.FF_ABOUT = ' + JSON.stringify(about, null, 1) + ';\n');
let html = R('index.html'), sessionHash = null;
html = html.replace(/<script src="([^"]+)"><\/script>/g, (m, src) => {
  let text = R(src);
  if (src.endsWith('session.js')) sessionHash = createHash('sha256').update(text).digest('hex');
  return '<script>' + text.replace(/<\/script/gi, '<\\/script') + '</script>';
});
writeFileSync(new URL('../' + NAME + '.html', here), html);
// the exit interview, in exactly TASK.md's shape
const ex = { sourceInformation: about.sourceInformation, testingFeedback: about.testingFeedback, engineFeedback: about.engineFeedback, promptFeedback: about.promptFeedback, aiHub: about.aiHub };
writeFileSync(new URL('../exit-interview.json', here), JSON.stringify(ex, null, 2) + '\n');
JSON.parse(R('../exit-interview.json'));
const vendorHash = createHash('sha256').update(R('vendor/session.js')).digest('hex');
const firstScript = html.indexOf('<script>'), sessionAt = html.indexOf('aihub-session 1.4.0');
console.log('wrote ../' + NAME + '.html (' + (html.length / 1024 / 1024).toFixed(2) + ' MB); session.js sha256 ' + sessionHash.slice(0, 16) + (sessionHash === vendorHash ? ' (matches vendor)' : ' (MISMATCH)') + (sessionAt > firstScript && sessionAt - firstScript < 120 && html.indexOf('<meta charset="utf-8">') < firstScript ? ', first script in <head>' : ', NOT FIRST'));
