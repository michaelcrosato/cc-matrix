import { spawn } from 'node:child_process';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const srv = spawn('python3', ['-u','-m','http.server','0','--bind','127.0.0.1'], { cwd: join(root,'tests/hub') });
let port=0;
await new Promise(res=>{const on=d=>{const m=String(d).match(/port (\d+)/); if(m){port=+m[1];res();}}; srv.stderr.on('data',on); srv.stdout.on('data',on); setTimeout(res,4000);});
console.log('port',port);
const pw = await import('playwright');
const browser = await pw.chromium.launch();
const hp = await browser.newPage();
hp.on('console', m=>console.log('[console]', m.type(), m.text().slice(0,200)));
hp.on('pageerror', e=>console.log('[pageerror]', String(e).slice(0,300)));
await hp.goto('http://127.0.0.1:'+port+'/harness.html?game=game.html&players=1&auto=1');
await hp.waitForTimeout(20000);
const state = await hp.evaluate(()=>({ complete: document.body.dataset.complete, check: window.__hubCheck ? {pass: window.__hubCheck.pass, checks: window.__hubCheck.checks} : null, round: document.querySelector('#round')?.textContent?.slice(0,500), checksText: document.querySelector('#checks')?.textContent?.slice(0,1500), log: document.querySelector('#log')?.textContent?.slice(-1500) }));
console.log(JSON.stringify(state,null,1).slice(0,4000));
await browser.close();
srv.kill('SIGTERM');
