// node tools/build.mjs [output.html]: bundles the game into one HTML file. session.js goes in unmodified, first in <head>.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, rmSync, existsSync } from 'node:fs';
import { dirname, resolve, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
process.chdir(root);
const out = process.argv[2] ?? resolve(root, '..', `${basename(root)}.html`);
const bundle = 'tools/.bundle.js';

// The exit interview is the one source of the About screen, so it and the chat reply can't drift apart.
const interview = resolve(root, '..', 'exit-interview.json');
const about = existsSync(interview) ? JSON.parse(readFileSync(interview, 'utf8')) : null;
const credits = readFileSync('src/CREDITS.md', 'utf8');
writeFileSync('src/game/data/about.gen.js', `// Generated by tools/build.mjs from exit-interview.json and the kit's CREDITS.md. Do not edit.\nexport const INTERVIEW = ${JSON.stringify(about)};\nexport const KIT_CREDITS = ${JSON.stringify(credits)};\n`);

execFileSync('esbuild', ['src/main.js', '--bundle', '--format=esm', '--target=esnext', '--charset=utf8', '--legal-comments=none', '--log-level=warning', `--outfile=${bundle}`], { stdio: 'inherit' });
const js = readFileSync(bundle, 'utf8').replace(/<\/script/gi, '<\\/script');
rmSync(bundle);
const session = readFileSync('tools/hub/session.js', 'utf8'); // the client, unmodified
const metas = readFileSync('tools/hub-metas.html', 'utf8');
const title = /export const TITLE = '([^']+)'/.exec(readFileSync('src/game/data/meta.js', 'utf8'))?.[1] ?? '';
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><script>${session}</script><title>${title}</title>
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover">
<link rel="icon" href="data:,">
${metas}
<style>html,body{margin:0;height:100%;background:#000;overflow:hidden}#row{display:flex;width:100vw;height:100vh}#p1{position:relative;width:100vw;height:100vh;overflow:hidden}#p2{display:none;position:relative;height:100vh;overflow:hidden}</style>
</head><body><div id="row"><div id="p1"></div><div id="p2"></div></div><script type="module">${js}</script></body></html>`;
writeFileSync(out, html);
console.log(`built ${out} (${(html.length / 1048576).toFixed(1)} MB)`);
