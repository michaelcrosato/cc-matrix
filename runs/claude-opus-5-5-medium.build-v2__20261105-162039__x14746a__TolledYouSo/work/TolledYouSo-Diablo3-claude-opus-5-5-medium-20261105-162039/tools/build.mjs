// node tools/build.mjs : generates about data, bundles with esbuild, writes the one HTML file in the root above the dev folder.
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url)); const dev = resolve(here, '..'); const root = resolve(dev, '..');
const NAME = 'TolledYouSo-Diablo3-claude-opus-5-5-medium-20261105-162039';
const out = join(root, `${NAME}.html`);
// About: one source of truth, the exit interview file.
const exitPath = join(root, 'exit-interview.json');
const clean = (s) => String(s).replace(/[—–]/g, '-').replace(/×/g, 'x').replace(/→/g, 'to').replace(/·/g, '-').replace(/[^\x20-\x7e\n]/g, '');
const ex = existsSync(exitPath) ? JSON.parse(readFileSync(exitPath, 'utf8')) : { sourceInformation: { usage: 'added on import' }, testingFeedback: [], engineFeedback: [], promptFeedback: [] };
const cleanDeep = (o) => (typeof o === 'string' ? clean(o) : Array.isArray(o) ? o.map(cleanDeep) : o && typeof o === 'object' ? Object.fromEntries(Object.entries(o).map(([k, v]) => [k, cleanDeep(v)])) : o);
const credits = clean(readFileSync(join(dev, 'CREDITS.md'), 'utf8')).split('\n').map((l) => l.replace(/[#*`]/g, '').replace(/\[([^\]]+)\]\([^)]*\)/g, '$1').trim()).filter(Boolean);
const about = { ...cleanDeep(ex), gameCredit: 'TOLLED YOU SO. AN ORIGINAL GAME ON THE PIXEL ENGINE KIT. THE KIT ASKS THAT ITS CREDITS SHIP WITH THE GAME:', credits };
const gen = join(dev, 'src/data/about.generated.js');
const text = `// Generated by tools/build.mjs from exit-interview.json. Do not edit.\nexport const ABOUT = ${JSON.stringify(about)};\n`;
if (!existsSync(gen) || readFileSync(gen, 'utf8') !== text) writeFileSync(gen, text);
execFileSync('esbuild', ['game.js', '--bundle', '--format=esm', '--target=es2022', '--charset=utf8', '--legal-comments=none', `--outfile=${join(dev, 'tools/.bundle.js')}`, '--log-level=error'], { cwd: dev, stdio: 'inherit' });
const bundle = readFileSync(join(dev, 'tools/.bundle.js'), 'utf8').replace(/<\/script/gi, '<\\/script');
const session = readFileSync(join(dev, 'session.js'), 'utf8');
const metas = {
  'hub:session': '1', 'hub:session-players': '1-4', 'hub:session-mode': 'shared-world', 'hub:session-minutes': '8',
  'hub:session-goal': 'Fill the Knell, then slay its Warden together', 'hub:session-howto': 'Move: stick or WASD. Attack: Cross or click. Skills: face buttons or 1-4.', 'hub:webgpu': 'required',
};
const html = `<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<script>${session}</script>
${Object.entries(metas).map(([k, v]) => `<meta name="${k}" content="${v}">`).join('\n')}
<title>Tolled You So</title>
<meta name="viewport" content="width=device-width,initial-scale=1">
<style>html,body{margin:0;background:#1a1c2c;overflow:hidden}#app{position:fixed;inset:0}</style>
</head><body><div id="app"></div>
<script type="module">${bundle}</script>
</body></html>
`;
writeFileSync(out, html);
if (!process.argv.includes('--quiet')) console.log(`${out} ${(statSync(out).size / 1048576).toFixed(1)} MB`);
