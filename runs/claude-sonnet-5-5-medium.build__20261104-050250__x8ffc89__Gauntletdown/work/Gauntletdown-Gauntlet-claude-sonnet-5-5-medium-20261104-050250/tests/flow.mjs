import { chromium } from 'playwright'; import { resolve } from 'node:path'; import { pathToFileURL } from 'node:url';
const b = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required', '--use-gl=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 1280, height: 720 } }); const errs = [];
p.on('pageerror', e => errs.push('PAGEERR ' + (e.stack || e).toString().slice(0, 500))); p.on('console', m => { if (m.type() === 'error') errs.push('CONSOLE ' + m.text().slice(0, 400)); });
await p.goto(pathToFileURL(resolve(process.argv[2] || 'game/index.html')).href); await p.waitForTimeout(1500);
const sc = () => p.evaluate(() => __gd.game.sceneName);
const shot = async n => { await p.screenshot({ path: `shots/flow-${n}.png` }); };
const key = async (k, w = 300) => { await p.keyboard.press(k); await p.waitForTimeout(w); };
console.log(await sc());
await key('Enter'); console.log(await sc()); await shot('menu');
await key('Enter'); console.log(await sc()); await p.waitForTimeout(500); await shot('select');
await key('ArrowRight'); await key('Enter'); await shot('select2');
await key('Enter', 600); console.log('after start', await sc()); await p.waitForTimeout(6000); await shot('card');
await key('Space', 500); await p.waitForTimeout(1500);
console.log(await p.evaluate(() => JSON.stringify(__gd.game.debug.snapshot())));
await p.keyboard.down('KeyD'); await p.keyboard.down('Space'); await p.waitForTimeout(3000); await p.keyboard.up('KeyD'); await p.keyboard.up('Space');
await shot('play');
await key('Escape', 700); await shot('pause'); console.log('paused', await p.evaluate(() => __gd.game.paused));
console.log(errs.length ? errs.join('\n') : 'no page errors');
await b.close();
